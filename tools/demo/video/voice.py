SR=22050; out=np.zeros(int(125*SR)); prev=0
for i,(t,txt) in enumerate(S):
    f=f"seg{i:02d}.wav"
    subprocess.run(["./piper/piper","-q","-m",M,"--length_scale","0.92","--sentence_silence","0.15","-f",f],input=txt.encode(),check=True)
    w=wave.open(f); a=np.frombuffer(w.readframes(w.getnframes()),np.int16)/32768; 
    nz=np.where(np.abs(a)>0.01)[0]; a=a[max(0,nz[0]-200):nz[-1]+2000]
    st=max(t,prev+0.35); d=len(a)/SR
    print(f"{i:2d} target {t:5.1f} start {st:5.1f} end {st+d:5.1f}" + ("  !!" if st-t>0.6 else ""))
    j=int(st*SR); out[j:j+len(a)]+=a[:len(out)-j]; prev=st+d
out=out/np.max(np.abs(out))*0.95
w=wave.open(OUT,'wb');w.setnchannels(1);w.setsampwidth(2);w.setframerate(SR);w.writeframes((out*32767).astype(np.int16).tobytes())
