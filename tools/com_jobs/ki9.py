# 21-31 (только чтение): виды КИ с удалённым родителем + группы + строки с удалёнными видами.
X = ib.XMLСтрока
R = q('ВЫБРАТЬ ВКИ.Ссылка КАК С, ВКИ.Наименование КАК Нм, ВКИ.ЭтоГруппа КАК Гр, ВКИ.Родитель КАК Р, ВКИ.Родитель.Наименование ЕСТЬ NULL И ВКИ.Родитель <> ЗНАЧЕНИЕ(Справочник.ВидыКонтактнойИнформации.ПустаяСсылка) КАК Битый, ВКИ.ИмяПредопределенныхДанных КАК ПД ИЗ Справочник.ВидыКонтактнойИнформации КАК ВКИ')
print('ГРУППЫ:')
for x in R:
    if x['Гр']: print('  G', x['Нм'][:50], '|', x['ПД'], '| родитель', s(x['Р'])[:30])
CATS = ['ФизическиеЛица', 'Партнеры', 'КонтактныеЛицаПартнеров', 'Контрагенты', 'Организации', 'Склады', 'Пользователи']
use = {}
for cat in CATS:
    try:
        for x in q('ВЫБРАТЬ КИ.Вид КАК Вд, КОЛИЧЕСТВО(*) КАК Кл ИЗ Справочник.' + cat + '.КонтактнаяИнформация КАК КИ СГРУППИРОВАТЬ ПО КИ.Вид'):
            use.setdefault(X(x['Вд']), []).append(f"{cat}:{x['Кл']}")
    except Exception as e: print('ERR', cat, str(e)[-60:])
br = [x for x in R if x['Битый']]
print('БЕЗ РОДИТЕЛЯ (родитель удалён):', len(br))
for x in sorted(br, key=lambda r: r['ПД'] or ''):
    print('  B', x['Нм'][:36], '|', x['ПД'], '| исп. в', use.get(X(x['С']), '-'), '| родитель', X(x['Р'])[:8])
# строки КИ с удалёнными видами
for cat in CATS:
    try:
        rows = q('ВЫБРАТЬ КИ.Ссылка КАК О, КИ.Вид КАК Вд, КИ.Представление КАК П ИЗ Справочник.' + cat + '.КонтактнаяИнформация КАК КИ ГДЕ КИ.Вид.Наименование ЕСТЬ NULL')
        for r in rows: print('  DEL-KIND', cat, s(r['О'])[:30], '|', X(r['Вд'])[:8], '|', (r['П'] or '')[:50])
    except Exception as e: print('ERR2', cat, str(e)[-60:])
