# 21-6: по решению пользователя (19:25) все документы «Корректировка регистров» в КОПИИ — пометка на удаление + снятие движений во всех регистрах.
docs = q("""ВЫБРАТЬ Д.Ссылка КАК Д ИЗ Документ.КорректировкаРегистров КАК Д ГДЕ НЕ Д.ПометкаУдаления""")
print("к пометке:", len(docs))
for r in docs:
    o = r["Д"].ПолучитьОбъект()
    n = 0
    for rn in ("ТоварыОрганизаций", "СебестоимостьТоваров", "ПрочиеАктивыПассивы", "ТоварыНаСкладах", "Хозрасчетный"):
        try:
            ns = getattr(o.Движения, rn)
        except Exception:
            continue
        ns.Прочитать()
        if ns.Количество() > 0:
            n += ns.Количество(); ns.Очистить(); ns.Записать()
    o = r["Д"].ПолучитьОбъект()
    o.УстановитьПометкуУдаления(True)
    log(f"21-6 Корректировка регистров: помечена на удаление {s(r['Д'])}, снято строк {n}")
left = q("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.ТоварыОрганизаций КАК Т ГДЕ Т.Регистратор ССЫЛКА Документ.КорректировкаРегистров")[0]["Н"]
left2 = q("ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Н ИЗ РегистрНакопления.СебестоимостьТоваров КАК Т ГДЕ Т.Регистратор ССЫЛКА Документ.КорректировкаРегистров")[0]["Н"]
print("осталось строк: ТоварыОрганизаций", left, "| СебестоимостьТоваров", left2)
