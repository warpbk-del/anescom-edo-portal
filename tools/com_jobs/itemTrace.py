# Чтение: история товара по обоим регистрам (ТоварыНаСкладах / ТоварыОрганизаций): документ, склад, кол-во. Параметры ITEM, WH (подстрока, можно "").
from collections import defaultdict
ITEM = globals().get("ITEM", "Профиль армирующий 1,2мм 207"); WH = globals().get("WH", "")
A = q("""ВЫБРАТЬ Т.Период КАК П, Т.Регистратор КАК Р, Т.Склад КАК С, СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.ВНаличии ИНАЧЕ -Т.ВНаличии КОНЕЦ) КАК К
ИЗ РегистрНакопления.ТоварыНаСкладах КАК Т ГДЕ Т.Активность И Т.Номенклатура.Наименование = &И СГРУППИРОВАТЬ ПО Т.Период, Т.Регистратор, Т.Склад""", И=ITEM)
B = q("""ВЫБРАТЬ Т.Период КАК П, Т.Регистратор КАК Р, Т.АналитикаУчетаНоменклатуры.Склад КАК С, СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Количество ИНАЧЕ -Т.Количество КОНЕЦ) КАК К
ИЗ РегистрНакопления.ТоварыОрганизаций КАК Т ГДЕ Т.Активность И Т.АналитикаУчетаНоменклатуры.Номенклатура.Наименование = &И СГРУППИРОВАТЬ ПО Т.Период, Т.Регистратор, Т.АналитикаУчетаНоменклатуры.Склад""", И=ITEM)
m = defaultdict(lambda: [0.0, 0.0, None])
for r in A:
    if WH in s(r["С"]):
        x = m[(s(r["Р"]), s(r["С"]))]; x[0] += r["К"]; x[2] = r["П"]
for r in B:
    if WH in s(r["С"]):
        x = m[(s(r["Р"]), s(r["С"]))]; x[1] += r["К"]; x[2] = r["П"]
bad = [(k, v) for k, v in m.items() if abs(v[0] - v[1]) > 0.0005]
print(f"{ITEM} / '{WH}': документов {len(m)}, с разными движениями {len(bad)}")
for (doc, wh), v in sorted(bad, key=lambda x: str(x[1][2]))[:40]:
    print(f"  {str(v[2])[:10]} {doc[:60]:<60} | {wh[:22]:<22} | скл {v[0]:>9.2f} орг {v[1]:>9.2f}")
