# (чтение) курсовые на 1710 по всем контрагентам ANESCOM: итог по контрагенту, затем строки Tianjin
T = {}
for r in q('ВЫБРАТЬ Х.Регистратор КАК Р, Х.Период КАК П, Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт, Х.Сумма КАК С, Х.СубконтоДт1 КАК СД, Х.СубконтоКт1 КАК СК ИЗ РегистрБухгалтерии.{REG}.ДвиженияССубконто(, , Организация.Наименование ПОДОБНО "%ANESCOM%" И (СчетДт.Код = "1710" ИЛИ СчетКт.Код = "1710"), , ) КАК Х УПОРЯДОЧИТЬ ПО Х.Период'):
    dt = r['Дт'] == '1710'; k = s(r['СД'] if dt else r['СК']); v = float(r['С']) * (1 if dt else -1)
    T[k] = T.get(k, 0) + v
    if 'Tianjin' in k: print(' ', str(r['П'])[:10], r['Дт'], r['Кт'], f'{v:>14,.2f}', s(r['Р'])[:45])
for k, v in sorted(T.items(), key=lambda x: x[1]):
    if abs(v) > 100: print('  ИТОГ', k[:40], f'{v:,.2f}')
