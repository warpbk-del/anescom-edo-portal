RES = collections.OrderedDict()   # код → (название, [строки dict])

def has(kind, nm, att):
    m = getattr(MD, kind).Найти(nm)
    if m is None: return False
    return m.Реквизиты.Найти(att) is not None or att in ('Ссылка', 'Дата', 'Номер', 'Проведен', 'ПометкаУдаления')
def tc_has(nm, tc, att):
    m = MD.Документы.Найти(nm); t = m.ТабличныеЧасти.Найти(tc) if m is not None else None
    return t is not None and t.Реквизиты.Найти(att) is not None
def author(nm):
    for a in ('Автор', 'Ответственный', 'Менеджер'):
        if has('Документы', nm, a): return a
    return None
def AU(nm, alias='Д'):
    a = author(nm); return f'{alias}.{a}' if a else 'НЕОПРЕДЕЛЕНО'
def first(kind, nm, cands):
    for c in cands:
        if has(kind, nm, c): return c
    return None
def add(code, title, rows):
    RES[code] = (title, rows); print(f'{code:14s} {len(rows):6d}  {title}', flush=True)
def run_check(code, title, fn):
    try: add(code, title, fn())
    except Exception as e:
        RES[code] = (title + ' — ОШИБКА ПРОВЕРКИ', [{'ошибка': str(e)[-300:]}]); print(f'{code:14s}  ERR {str(e)[-160:]}', flush=True)
def docrows(text, **p):
    out = []
    for r in q(text, **p):
        d = {}
        for k, v in r.items():
            if k == 'Ссылка': d['документ'] = s(v)
            elif isinstance(v, (int, float, str)) or v is None: d[k] = v
            elif hasattr(v, 'year'): d[k] = datetime.datetime(v.year, v.month, v.day, v.hour, v.minute)
            else: d[k] = s(v)
        out.append(d)
    return out

