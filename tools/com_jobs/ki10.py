# 21-31 исправление (ANESCOM_FIX): виды КИ с удалённым родителем → в штатные группы; создать «Телефон родственника».
# DRY=True по умолчанию.
X = ib.XMLСтрока
DRY = globals().get('DRY', True)
R = q('ВЫБРАТЬ ВКИ.Ссылка КАК С, ВКИ.Наименование КАК Нм, ВКИ.ЭтоГруппа КАК Гр, ВКИ.Родитель КАК Р, ВКИ.Родитель.Наименование ЕСТЬ NULL И ВКИ.Родитель <> ЗНАЧЕНИЕ(Справочник.ВидыКонтактнойИнформации.ПустаяСсылка) КАК Битый, ВКИ.ИмяПредопределенныхДанных КАК ПД ИЗ Справочник.ВидыКонтактнойИнформации КАК ВКИ')
G = {x['ПД']: x['С'] for x in R if x['Гр'] and x['ПД']}
GFL, GK = G['СправочникФизическиеЛица'], G['СправочникКонтрагенты']
n = 0
for x in R:
    if not x['Битый']: continue
    pd = x['ПД'] or ''
    tgt = GFL if pd.endswith('ФизическиеЛица') else (GK if ('Контрагент' in pd) else None)
    if tgt is None:
        print('SKIP (не понял группу)', x['Нм'], pd); continue
    ob = x['С'].ПолучитьОбъект()
    print('MOVE', x['Нм'][:36], '|', pd, '→', s(tgt)[:45], '| исп.', ob.Используется)
    if not DRY:
        ob.Родитель = tgt
        if not ob.Используется: ob.Используется = True
        ob.ОбменДанными.Загрузка = True; ob.Записать()
    n += 1
# «Телефон родственника» в группе физлиц
ex = [x for x in R if not x['Гр'] and X(x['Р']) == X(GFL) and x['Нм'].strip().lower() == 'телефон родственника']
if ex:
    print('EXISTS Телефон родственника')
else:
    obr = q('ВЫБРАТЬ ВКИ.Ссылка КАК С ИЗ Справочник.ВидыКонтактнойИнформации КАК ВКИ ГДЕ ВКИ.ИмяПредопределенныхДанных = "ТелефонДомашнийФизическиеЛица"')[0]['С']
    print('CREATE Телефон родственника (по образцу «Домашний телефон»)')
    if not DRY:
        nw = obr.Скопировать()
        nw.Наименование = 'Телефон родственника'; nw.Родитель = GFL; nw.Используется = True
        try: nw.ИмяПредопределенногоВида = ''
        except Exception: pass
        nw.ОбменДанными.Загрузка = True; nw.Записать()
print('DRY' if DRY else 'WRITE', 'перемещено видов', n)
if not DRY: log(f'21-31 ki10: виды КИ без родителя возвращены в группы ({n}), создан «Телефон родственника»')
