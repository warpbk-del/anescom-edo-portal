# Исключить авансы выданные (1710) из переоценки, как авансы полученные (3510). DRY=1 — показать флаги.
DRY = globals().get('DRY', 1)
PL = ib.Метаданные.РегистрыБухгалтерии.Получить(0).ПланСчетов.Имя
for r in q(f'ВЫБРАТЬ С.Ссылка КАК С, С.Код КАК К ИЗ ПланСчетов.{PL} КАК С ГДЕ С.Код ПОДОБНО "171%" ИЛИ С.Код ПОДОБНО "351%" ИЛИ С.Код ПОДОБНО "121%" ИЛИ С.Код ПОДОБНО "331%" УПОРЯДОЧИТЬ ПО С.Код'):
    a = r['С']
    if not a.Валютный: continue
    print(' ', r['К'], 'искл.БУ', s(a.ИсключитьСуммуБУИзПереоценкиПоПлануСчетов), 'искл.УУ', s(a.ИсключитьСуммуУУИзПереоценкиПоПлануСчетов), s(a.Наименование)[:40])
    if not DRY and r['К'].startswith('171') and not a.ИсключитьСуммуБУИзПереоценкиПоПлануСчетов:
        o = a.ПолучитьОбъект(); o.ИсключитьСуммуБУИзПереоценкиПоПлануСчетов = True; o.Записать(); print('    → исключён из переоценки')
