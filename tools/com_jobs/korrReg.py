# Чтение: документы «Корректировка регистров» — какие регистры правят, и сколько расхождения склад/организация они дают.
from collections import defaultdict
docs = q("""ВЫБРАТЬ Д.Ссылка КАК Д, Д.Дата КАК Дт, Д.Проведен КАК П, Д.ПометкаУдаления КАК У, Д.Комментарий КАК К, Д.Ответственный КАК О ИЗ Документ.КорректировкаРегистров КАК Д УПОРЯДОЧИТЬ ПО Д.Дата""")
print("Корректировок регистров:", len(docs), "| проведено", sum(1 for d in docs if d["П"]), "| помечено", sum(1 for d in docs if d["У"]))
regs = []
mt = ib.Метаданные.Документы.КорректировкаРегистров
for coll in (ib.Метаданные.РегистрыНакопления, ib.Метаданные.РегистрыБухгалтерии, ib.Метаданные.РегистрыСведений):
    for i in range(coll.Количество()):
        rm = coll.Получить(i)
        try:
            if mt.Движения.Содержит(rm):
                regs.append(rm.ПолноеИмя())
        except Exception:
            pass
cnt = defaultdict(lambda: [0, set()])
for rn in regs:
    try:
        rs = q(f"ВЫБРАТЬ Т.Регистратор КАК Р, КОЛИЧЕСТВО(*) КАК Н ИЗ {rn} КАК Т ГДЕ Т.Регистратор ССЫЛКА Документ.КорректировкаРегистров СГРУППИРОВАТЬ ПО Т.Регистратор")
    except Exception:
        continue
    for r in rs:
        cnt[rn][0] += r["Н"]; cnt[rn][1].add(s(r["Р"]))
print("== регистры, которые правились (строк | документов):")
for rn, (n, ds) in sorted(cnt.items(), key=lambda x: -x[1][0]):
    print(f"  {rn[:60]:<60} {n:>6} {len(ds):>4}")
print("== документы:")
for d in docs:
    regs_d = [rn.split(".")[-1] for rn, (n, ds) in cnt.items() if s(d["Д"]) in ds]
    print(f"  {s(d['Д'])[-34:]:<34} {'пров' if d['П'] else '----'} {'УДАЛ' if d['У'] else ''} | {s(d['О'])[:18]:<18} | {str(d['К'])[:40]:<40} | {','.join(regs_d)[:80]}")
