# Чтение: реквизиты ТЧ «Производство без заказа» и строки документа 00НФ-000004 от 03.03.2025 (W45.10.07)
m = ib.Метаданные.Документы.Найти("ПроизводствоБезЗаказа")
for j in range(m.ТабличныеЧасти.Количество()):
    tp = m.ТабличныеЧасти.Получить(j)
    print(tp.Имя, ":", ",".join(tp.Реквизиты.Получить(i).Имя for i in range(tp.Реквизиты.Количество())))
d = q("""ВЫБРАТЬ Д.Ссылка КАК Д ИЗ Документ.ПроизводствоБезЗаказа КАК Д ГДЕ Д.Номер = "00НФ-000004" И Д.Дата МЕЖДУ &Н И &К""",
      Н=datetime.datetime(2025, 3, 1), К=datetime.datetime(2025, 3, 31, 23, 59, 59))
for r in d:
    o = r["Д"].ПолучитьОбъект(); tp = o.МатериалыИРаботы
    tm = m.ТабличныеЧасти.Найти("МатериалыИРаботы")
    names = [tm.Реквизиты.Получить(i).Имя for i in range(tm.Реквизиты.Количество())]
    print(s(r["Д"]), "строк", tp.Количество())
    for i in range(tp.Количество()):
        row = tp.Получить(i)
        nom = s(row.Номенклатура)
        if "W45.10.07" in nom or i < 2:
            print(i, " | ".join(f"{n}={s(getattr(row, n))}" for n in names if s(getattr(row, n))))
