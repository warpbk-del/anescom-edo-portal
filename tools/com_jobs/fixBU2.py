def rows_of(acc):
    return q(f"""ВЫБРАТЬ О.Организация КАК Орг, О.Подразделение КАК П, О.Субконто1 КАК С1, О.Субконто2 КАК С2, О.Субконто3 КАК С3,
      О.СуммаОстатокДт - О.СуммаОстатокКт КАК Ост ИЗ РегистрБухгалтерии.{{REG}}.Остатки(&Д, Счет.Код = "{acc}", , ) КАК О""", Д=D)
def plan(debt_acc, adv_acc, debt_sign):
    debt = [r for r in rows_of(debt_acc) if debt_sign * float(r["Ост"]) > 0.009]
    adv = {}
    for r in rows_of(adv_acc):
        if -debt_sign * float(r["Ост"]) > 0.009: adv.setdefault((s(r["Орг"]), s(r["С1"]), s(r["С2"])), []).append([r, abs(float(r["Ост"]))])
    pl = []
    for r in debt:
        left = abs(float(r["Ост"]))
        for a in adv.get((s(r["Орг"]), s(r["С1"]), s(r["С2"])), []):
            amt = round(min(left, a[1]), 2)
            if amt > 0.009: pl.append((a[0], r, amt)); left -= amt; a[1] -= amt
            if left <= 0.009: break
    return pl
