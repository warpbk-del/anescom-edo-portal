# Ручные корректировки проводок (ANESCOM_FIX): «Отражено вручную» → «К отражению» (проводки пересоберёт штатное отражение).
# DRY=True: разбивка + бэкап проводок в CSV. Запись: меняется только статус в РС ОтражениеДокументовВРеглУчете.
import collections, csv
DRY = globals().get('DRY', True)
MDR = MD.РегистрыСведений.ОтражениеДокументовВРеглУчете
EN = MD.Перечисления.СтатусыОтраженияДокументовВРеглУчете
VAL = {EN.ЗначенияПеречисления.Получить(i).Имя: getattr(ib.Перечисления.СтатусыОтраженияДокументовВРеглУчете, EN.ЗначенияПеречисления.Получить(i).Имя) for i in range(EN.ЗначенияПеречисления.Количество())}
print('статусы', list(VAL))
MAN = [v for k, v in VAL.items() if 'ручн' in k.lower()][0]
TO = [v for k, v in VAL.items() if k.lower().startswith('котраж') or k == 'КОтражению'][0]
R = q('ВЫБРАТЬ О.Регистратор КАК Д, О.Организация КАК Орг, О.ДатаОтражения КАК Дт, О.Комментарий КАК Км ИЗ РегистрСведений.ОтражениеДокументовВРеглУчете КАК О ГДЕ О.Статус = &С', С=MAN)
c = collections.Counter(); y = collections.Counter(); o = collections.Counter()
for r in R:
    v = s(r['Д']); c[v.split(' 0')[0].split(' ГТ')[0][:40]] += 1; y[str(r['Дт'])[:7]] += 1; o[s(r['Орг'])[:30]] += 1
print('ВСЕГО', len(R)); print(' виды:', c.most_common(12)); print(' организации:', o.most_common()); print(' по месяцам:', sorted(y.items()))
# бэкап проводок этих документов
out = r'D:\anescom_edo\data\reports\ручные_проводки_бэкап_26-10-2026.csv'
n = 0
with open(out, 'w', encoding='utf-8-sig', newline='') as f:
    w = csv.writer(f, delimiter=';'); w.writerow(['Документ', 'Период', 'Организация', 'СчетДт', 'СчетКт', 'Сумма', 'Содержание'])
    arr = ib.NewObject('Массив')
    for r in R: arr.Добавить(r['Д'])
    for p in q('ВЫБРАТЬ Х.Регистратор КАК Д, Х.Период КАК П, Х.Организация КАК О, Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт, Х.Сумма КАК С, Х.Содержание КАК Сд ИЗ РегистрБухгалтерии.{REG} КАК Х ГДЕ Х.Регистратор В (&А)', А=arr):
        w.writerow([s(p['Д']), str(p['П']), s(p['О']), p['Дт'], p['Кт'], p['С'], p['Сд']]); n += 1
print('БЭКАП проводок', n, '→', out)
if not DRY:
    done = 0
    for r in R:
        ns = ib.РегистрыСведений.ОтражениеДокументовВРеглУчете.СоздатьНаборЗаписей()
        ns.Отбор.Регистратор.Установить(r['Д']); ns.Прочитать()
        for i in range(ns.Количество()):
            z = ns.Получить(i)
            if z.Статус == MAN: z.Статус = TO
        ns.ОбменДанными.Загрузка = True; ns.Записать(); done += 1
    print('WRITE статус «К отражению»:', done)
    log(f'ручные корректировки → К отражению: {done}, бэкап проводок {n} строк {out}')
