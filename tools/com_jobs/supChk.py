# Чтение (21-23): поставщики — где БУ (3310/1610) расходится с оперативным (РасчетыСПоставщиками), по видам документов, 01–06.2025
N0 = datetime.datetime(2025, 1, 1, 6); D = datetime.datetime(2025, 7, 1, 6)
for name in ("АВТОКОМП", "Иманғалиева", "АЛЬТЕРНАТИВА", "Тарханова", "Жас Строй"):
    bu = {}
    for r in q("""ВЫБРАТЬ ТИПЗНАЧЕНИЯ(О.Регистратор) КАК Т, СУММА(О.СуммаОборотДт) КАК Дт, СУММА(О.СуммаОборотКт) КАК Кт
      ИЗ РегистрБухгалтерии.{REG}.Обороты(&Н, &Д, Регистратор, Счет.Код ПОДОБНО "3310%" ИЛИ Счет.Код ПОДОБНО "1610%", , , , ) КАК О
      ГДЕ О.Субконто1.Наименование ПОДОБНО &И СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(О.Регистратор)""", Н=N0, Д=D, И=f"%{name}%"):
        bu[s(r["Т"])] = float(r["Дт"] or 0) - float(r["Кт"] or 0)
    op = {}
    for r in q("""ВЫБРАТЬ ТИПЗНАЧЕНИЯ(Р.Регистратор) КАК Т, СУММА(Р.СуммаПриход - Р.СуммаРасход) КАК С
      ИЗ РегистрНакопления.РасчетыСПоставщиками.Обороты(&Н, &Д, Регистратор, ) КАК Р
      ГДЕ Р.АналитикаУчетаПоПартнерам.Контрагент.Наименование ПОДОБНО &И СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(Р.Регистратор)""", Н=N0, Д=D, И=f"%{name}%"):
        op[s(r["Т"])] = float(r["С"] or 0)
    ob = q("""ВЫБРАТЬ СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК О ИЗ РегистрБухгалтерии.{REG}.Остатки(&Н, Счет.Код ПОДОБНО "3310%" ИЛИ Счет.Код ПОДОБНО "1610%", , ) КАК О
      ГДЕ О.Субконто1.Наименование ПОДОБНО &И""", Н=N0, И=f"%{name}%")[0]["О"]
    oo = q("""ВЫБРАТЬ СУММА(Р.СуммаОстаток) КАК О ИЗ РегистрНакопления.РасчетыСПоставщиками.Остатки(&Н, АналитикаУчетаПоПартнерам.Контрагент.Наименование ПОДОБНО &И) КАК Р""", Н=N0, И=f"%{name}%")[0]["О"]
    print(f"=== {name}: нач. БУ {float(ob or 0)/1e6:,.2f} | нач. опер {float(oo or 0)/1e6:,.2f}")
    for t in sorted(set(bu) | set(op)):
        print(f"   {t[:45]:45} БУ(Дт-Кт) {bu.get(t, 0)/1e6:10,.2f}   опер(+приход) {op.get(t, 0)/1e6:10,.2f}")
