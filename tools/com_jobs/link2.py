# 21-35: оплаты поставщикам без «ДокументОснование» → приобретение (или заказ поставщику) с той же суммой, контрагентом, договором; дата −60…+30 дн.; только однозначные.
# Запись: только реквизит ДокументОснование (ОбменДанными.Загрузка, без перепроведения — проводки и расчёты не меняются). DRY=True.
import collections
DRY = globals().get('DRY', True)
m = MD.Документы.СписаниеБезналичныхДенежныхСредств.Реквизиты.Найти('ДокументОснование')
allowed = {ib.Метаданные.НайтиПоТипу(m.Тип.Типы().Получить(i)).Имя for i in range(m.Тип.Типы().Количество()) if ib.Метаданные.НайтиПоТипу(m.Тип.Типы().Получить(i)) is not None}
print('ДокументОснование допускает: приобретение', 'ПриобретениеТоваровУслуг' in allowed, '| заказ', 'ЗаказПоставщику' in allowed, '| услуги', 'ПриобретениеУслугПрочихАктивов' in allowed)
N = datetime.datetime(2025, 1, 1)
P = q('ВЫБРАТЬ Д.Ссылка КАК С, Д.Дата КАК Дт, Д.Контрагент КАК К, Д.СуммаДокумента КАК Сум, Д.Договор КАК Дг ИЗ Документ.СписаниеБезналичныхДенежныхСредств КАК Д '
      'ГДЕ Д.Проведен И Д.Дата >= &Н И Д.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ОплатаПоставщику) И (Д.ДокументОснование = НЕОПРЕДЕЛЕНО ИЛИ Д.ДокументОснование.Ссылка ЕСТЬ NULL)', Н=N)
X = ib.XMLСтрока
def load(doc):
    idx = collections.defaultdict(list)
    for r in q(f'ВЫБРАТЬ Д.Ссылка КАК С, Д.Дата КАК Дт, Д.Контрагент КАК К, Д.СуммаДокумента КАК Сум ИЗ Документ.{doc} КАК Д ГДЕ Д.Проведен И Д.Дата >= &Н', Н=N - datetime.timedelta(days=60)):
        idx[(X(r['К']), round(float(r['Сум'] or 0), 2))].append(r)
    return idx
IDX = [(d, load(d)) for d in ('ПриобретениеТоваровУслуг', 'ПриобретениеУслугПрочихАктивов', 'ЗаказПоставщику') if d in allowed]
used = set(); plan = []; amb = 0; none = 0
for p in P:
    key = (X(p['К']), round(float(p['Сум'] or 0), 2)); pd = p['Дт']; hit = None
    for d, idx in IDX:
        c = [r for r in idx.get(key, []) if X(r['С']) not in used and -30 <= (datetime.datetime(pd.year, pd.month, pd.day) - datetime.datetime(r['Дт'].year, r['Дт'].month, r['Дт'].day)).days <= 60]
        if len(c) == 1: hit = (d, c[0]); break
        if len(c) > 1: amb += 1; hit = 'amb'; break
    if hit is None: none += 1; continue
    if hit == 'amb': continue
    used.add(X(hit[1]['С'])); plan.append((p, hit[0], hit[1]))
cnt = collections.Counter(d for _, d, _ in plan)
print('оплат без основания', len(P), '| найдено однозначно', len(plan), dict(cnt), '| неоднозначно', amb, '| не найдено', none)
for p, d, r in plan[:8]: print(f"  {s(p['С'])[:55]} {float(p['Сум']):>14,.2f} → {s(r['С'])[:60]}")
if not DRY:
    ok = err = 0
    for p, d, r in plan:
        try:
            o = p['С'].ПолучитьОбъект(); o.ДокументОснование = r['С']; o.ОбменДанными.Загрузка = True; o.Записать(); ok += 1
        except Exception as e: err += 1
    print('WRITE связано', ok, 'ошибок', err)
    log(f'21-35 оплаты поставщикам → ДокументОснование: {ok} ({dict(cnt)}), ошибок {err}')
