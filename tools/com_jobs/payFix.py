# 21-13 ИСПРАВЛЕНИЕ (копия): висящие оплаты поставщикам (объект расчётов = сам платёж) -> договор поставщика,
# только если договор однозначен (один в оплатах этого поставщика или один в справочнике). Перепровести. Комментарий «[аудит 24.10.2026]».
from collections import defaultdict
hang = q("""ВЫБРАТЬ РАЗЛИЧНЫЕ Д.Ссылка КАК Док, Д.Ссылка.Дата КАК Дата, Д.Ссылка.Организация КАК Орг, Д.Ссылка.Контрагент КАК Кт
ИЗ Документ.СписаниеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК Д
ГДЕ Д.Ссылка.Проведен И Д.Ссылка.Дата >= &Н И Д.Ссылка.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ОплатаПоставщику)
 И Д.Заказ ССЫЛКА Документ.СписаниеБезналичныхДенежныхСредств
УПОРЯДОЧИТЬ ПО Д.Ссылка.Дата""", Н=datetime.datetime(2025, 1, 1))
pay = defaultdict(dict)
for r in q("""ВЫБРАТЬ РАЗЛИЧНЫЕ Д.Ссылка.Организация КАК Орг, Д.Ссылка.Контрагент КАК Кт, Д.Заказ КАК Дог
ИЗ Документ.СписаниеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК Д
ГДЕ Д.Ссылка.Проведен И Д.Заказ ССЫЛКА Справочник.ДоговорыКонтрагентов"""):
    pay[(s(r["Орг"]), s(r["Кт"]))][s(r["Дог"])] = r["Дог"]
cat = defaultdict(dict)
for r in q("""ВЫБРАТЬ Д.Организация КАК Орг, Д.Контрагент КАК Кт, Д.Ссылка КАК Дог ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ НЕ Д.ПометкаУдаления"""):
    cat[(s(r["Орг"]), s(r["Кт"]))][s(r["Дог"])] = r["Дог"]
hdr = [ib.Метаданные.Документы.Найти("СписаниеБезналичныхДенежныхСредств").Реквизиты.Получить(i).Имя
       for i in range(ib.Метаданные.Документы.Найти("СписаниеБезналичныхДенежныхСредств").Реквизиты.Количество())]
ok = skip = err = 0; first = None
for r in hang:
    k = (s(r["Орг"]), s(r["Кт"]))
    c = pay.get(k) if len(pay.get(k, {})) == 1 else (cat.get(k) if not pay.get(k) and len(cat.get(k, {})) == 1 else None)
    if not c:
        skip += 1; print("ПРОПУСК (нет однозначного договора)", s(r["Док"])[-40:], k[1][:40]); continue
    dog = list(c.values())[0]
    o = r["Док"].ПолучитьОбъект(); n = 0
    for i in range(o.РасшифровкаПлатежа.Количество()):
        row = o.РасшифровкаПлатежа.Получить(i)
        if s(row.Заказ) == s(r["Док"]) or "Списание безналичных" in s(row.Заказ):
            row.Заказ = dog; n += 1
    if "Договор" in hdr and not s(o.Договор):
        o.Договор = dog
    if "[аудит 24.10.2026]" not in o.Комментарий:
        o.Комментарий = (o.Комментарий + " [аудит 24.10.2026]").strip()
    try:
        o.Записать(ib.РежимЗаписиДокумента.Проведение); ok += 1
        first = first or s(r["Дата"])[:10]
        log(f"21-13 оплата привязана к договору ({n} стр.): {s(r['Док'])} -> {s(dog)[:60]}")
    except Exception as e:
        err += 1; print("ОШИБКА", s(r["Док"])[-40:], str(e)[-150:])
print(f"исправлено {ok}, пропущено {skip}, ошибок {err}; самая ранняя дата исправленного: {first}")
