# Остатки «к отгрузке / к поступлению / распоряжения» — по регистрам, если есть
def pending():
    for nm in ("ТоварыКОтгрузке", "ТоварыКПоступлению", "ЗаказыКлиентов", "ЗаказыПоставщикам", "ТоварыКОформлениюОтчетовКомитенту",
               "ДенежныеСредстваКВыплате", "ДенежныеСредстваКПоступлению", "РасчетыСПодотчетниками"):
        m = MD.РегистрыНакопления.Найти(nm)
        if m is None or s(m.ВидРегистра) not in ("Остатки",) and str(m.ВидРегистра) not in ("Остатки",):
            if m is None: continue
        res = [m.Ресурсы.Получить(j).Имя for j in range(m.Ресурсы.Количество())]
        try:
            r = q(f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К, " + ", ".join(f"СУММА(Р.{x}Остаток) КАК {x}" for x in res[:4]) + f" ИЗ РегистрНакопления.{nm}.Остатки КАК Р")[0]
            print(f"[рег] {nm}: строк {r['К']};", ", ".join(f"{x} {float(r[x] or 0):,.0f}" for x in res[:4]))
        except Exception as e:
            print(f"[рег] {nm}: не остаточный/ошибка", str(e)[-80:])
check("остатки регистров", pending)

