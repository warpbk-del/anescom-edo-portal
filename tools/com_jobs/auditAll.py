def save(name, head, rows):
    with open(os.path.join(OUT, name + ".csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";"); w.writerow(head)
        for r in rows: w.writerow([str(x).replace(".", ",") if isinstance(x, float) else x for x in r])

def attrs(m):
    return {m.Реквизиты.Получить(i).Имя for i in range(m.Реквизиты.Количество())}

def check(title, fn):
    try:
        fn()
    except Exception as e:
        print(f"[{title}] ОШИБКА проверки:", str(e)[-160:])

# 9. Общее: непроведённые, проведённые с пометкой, будущие даты — по всем видам документов
def general():
    unp, delp, fut = [], [], []
    for i in range(MD.Документы.Количество()):
        m = MD.Документы.Получить(i)
        if str(m.Проведение) != "Разрешить" and s(m.Проведение) != "Разрешить":
            continue
        try:
            r = q(f"""ВЫБРАТЬ
             СУММА(ВЫБОР КОГДА НЕ Д.Проведен И НЕ Д.ПометкаУдаления ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Неп,
             СУММА(ВЫБОР КОГДА Д.Проведен И Д.ПометкаУдаления ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Пом,
             СУММА(ВЫБОР КОГДА Д.Дата > &Т И НЕ Д.ПометкаУдаления ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК Буд
            ИЗ Документ.{m.Имя} КАК Д ГДЕ Д.Дата >= &Н""", Н=N, Т=NOW)[0]
        except Exception:
            continue
        if r["Неп"]: unp.append((m.Синоним or m.Имя, int(r["Неп"])))
        if r["Пом"]: delp.append((m.Синоним or m.Имя, int(r["Пом"])))
        if r["Буд"]: fut.append((m.Синоним or m.Имя, int(r["Буд"])))
    for t, lst in (("непроведённые (не помечены)", unp), ("проведённые С пометкой удаления", delp), ("будущими датами", fut)):
        lst.sort(key=lambda x: -x[1])
        print(f"[9] {t}: видов {len(lst)}, док. {sum(x[1] for x in lst)}; топ:", "; ".join(f"{a} {b}" for a, b in lst[:6]))
    save("9_непроведенные", ["Вид", "Кол-во"], unp); save("9_проведенные_с_пометкой", ["Вид", "Кол-во"], delp); save("9_будущие_даты", ["Вид", "Кол-во"], fut)
check("общее", general)

