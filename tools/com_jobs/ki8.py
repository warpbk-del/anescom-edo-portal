# 21-31 восстановление видов КИ физлиц (ANESCOM_FIX). По умолчанию DRY=True — только показывает.
# Нужно, чтобы в группе видов «Физические лица» были и использовались:
#   Адрес по прописке, Адрес проживания, Телефон мобильный, Домашний телефон, Телефон родственника, Email.
X = ib.XMLСтрока
DRY = globals().get('DRY', True)
def attr(o, n, d=None):
    try: return getattr(o, n)
    except Exception: return d
ALL = q('ВЫБРАТЬ ВКИ.Ссылка КАК С, ВКИ.Наименование КАК Нм, ВКИ.Родитель КАК Р, ВКИ.ЭтоГруппа КАК Гр ИЗ Справочник.ВидыКонтактнойИнформации КАК ВКИ')
def pd(o):  # имя предопределённого (платформа или БСП 3)
    return (attr(o, 'ИмяПредопределенныхДанных', '') or '') + '/' + (attr(o, 'ИмяПредопределенногоВида', '') or '')
# группа видов физлиц
G = None
for x in ALL:
    if x['Гр'] and ('СправочникФизическиеЛица' in pd(x['С']) or x['Нм'].strip().lower() == 'физические лица'):
        G = x['С']; break
print('GROUP', s(G), pd(G) if G else '')
T = ib.Перечисления.ТипыКонтактнойИнформации
NEED = [('Адрес по прописке', 'АдресПоПропискеФизическиеЛица', T.Адрес),
        ('Адрес проживания', 'АдресМестаПроживанияФизическиеЛица', T.Адрес),
        ('Телефон мобильный', 'ТелефонМобильныйФизическиеЛица', T.Телефон),
        ('Домашний телефон', 'ТелефонДомашнийФизическиеЛица', T.Телефон),
        ('Телефон родственника', None, T.Телефон),
        ('Email', 'EMailФизическиеЛица', T.АдресЭлектроннойПочты)]
cnt = {X(x['В']): x['К'] for x in q('ВЫБРАТЬ КИ.Вид КАК В, КОЛИЧЕСТВО(*) КАК К ИЗ Справочник.ФизическиеЛица.КонтактнаяИнформация КАК КИ СГРУППИРОВАТЬ ПО КИ.Вид')}
order = 0
for nm, pname, tp in NEED:
    order += 1
    hit = None
    for x in ALL:
        if x['Гр']: continue
        if pname and pname.lower() in pd(x['С']).lower(): hit = x; break
    if hit is None:
        for x in ALL:
            if not x['Гр'] and X(x['Р']) == X(G) and x['Нм'].strip().lower() == nm.lower(): hit = x; break
    if hit is None:
        print('CREATE', nm, s(tp))
        if not DRY:
            ob = ib.Справочники.ВидыКонтактнойИнформации.СоздатьЭлемент()
            ob.Родитель = G; ob.Наименование = nm; ob.Тип = tp; ob.Используется = True
            try: ob.РазрешитьВводНесколькихЗначений = True
            except Exception: pass
            ob.ОбменДанными.Загрузка = True; ob.Записать()
        continue
    ob = hit['С'].ПолучитьОбъект()
    ch = []
    if X(ob.Родитель) != X(G): ch.append('Родитель ' + s(ob.Родитель) + '→' + s(G)); ob.Родитель = G
    if not attr(ob, 'Используется', True): ch.append('Используется→Да'); ob.Используется = True
    if ob.ПометкаУдаления: ch.append('снять пометку'); ob.ПометкаУдаления = False
    if ob.Наименование.strip() != nm: ch.append('имя «' + ob.Наименование + '»→«' + nm + '»'); ob.Наименование = nm
    print('KIND', nm, '| сейчас', hit['Нм'], '|', pd(hit['С']), '| строк', cnt.get(X(hit['С']), 0), '|', ch or 'OK')
    if ch and not DRY:
        ob.ОбменДанными.Загрузка = True; ob.Записать()
print('DRY' if DRY else 'WRITE')
if not DRY: log('21-31 восстановлены виды КИ физлиц (ki8)')
