# Чтение (21-14): какие регистры стоят за вкладками «К поступлению» и «К оплате / переводу», их остатки
M = ib.Метаданные
for coll, kind in ((M.РегистрыНакопления, "РН"), (M.РегистрыСведений, "РС")):
    for i in range(coll.Количество()):
        r = coll.Получить(i); n = r.Имя
        if any(x in n for x in ("КПоступлению", "КОплате", "КВыплате", "ГрафикПлатеж", "ПланОплат", "ПланПоступлен", "РасчетыСПоставщикамиПоСрокам", "РасчетыСКлиентамиПоСрокам", "РасчетыСПоставщикамиПланОплат", "РасчетыСКлиентамиПланОплат")):
            d = ",".join(r.Измерения.Получить(j).Имя for j in range(r.Измерения.Количество()))
            res = ",".join(r.Ресурсы.Получить(j).Имя for j in range(r.Ресурсы.Количество()))
            print(kind, n, "| изм:", d, "| рес:", res)
