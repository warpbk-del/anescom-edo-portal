# 21-15 исправления (копия): (в) договоры без порядка расчётов -> «по договорам»; (б) поступления от клиентов, где объект = сам платёж -> договор;
# (а) заказы поставщикам старше 60 дн. в незакрытых статусах -> «Закрыт» (с перепроведением);
# (а2) заказы клиентов «На согласовании» старше 60 дн. -> «Закрыт» (движений у таких заказов нет -> запись без перепроведения, режим загрузки).
from collections import defaultdict
STEPS = globals().get("STEPS", "вба")
D60 = datetime.datetime.now() - datetime.timedelta(days=60)
TAG = "[аудит 24.10.2026]"
def tag(o):
    if TAG not in o.Комментарий: o.Комментарий = (o.Комментарий + " " + TAG).strip()

if "в" in STEPS:
    n = 0
    for r in q("""ВЫБРАТЬ Д.Ссылка КАК Д ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ НЕ Д.ПометкаУдаления
       И Д.ПорядокРасчетов = ЗНАЧЕНИЕ(Перечисление.ПорядокРасчетов.ПустаяСсылка)"""):
        o = r["Д"].ПолучитьОбъект(); o.ПорядокРасчетов = ib.Перечисления.ПорядокРасчетов.ПоДоговорамКонтрагентов
        try: o.Записать(); n += 1
        except Exception as e: print("ОШИБКА договор", s(r["Д"])[:50], str(e)[-120:])
    log(f"21-15в договоры без порядка расчётов -> «по договорам»: {n}")

if "б" in STEPS:
    hang = q("""ВЫБРАТЬ РАЗЛИЧНЫЕ Д.Ссылка КАК Док, Д.Ссылка.Организация КАК Орг, Д.Ссылка.Контрагент КАК Кт
    ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК Д
    ГДЕ Д.Ссылка.Проведен И Д.Ссылка.Дата >= &Н И Д.Заказ ССЫЛКА Документ.ПоступлениеБезналичныхДенежныхСредств""", Н=datetime.datetime(2025, 1, 1))
    pay, cat = defaultdict(dict), defaultdict(dict)
    for r in q("""ВЫБРАТЬ РАЗЛИЧНЫЕ Д.Ссылка.Организация КАК Орг, Д.Ссылка.Контрагент КАК Кт, Д.Заказ КАК Дог
      ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК Д ГДЕ Д.Ссылка.Проведен И Д.Заказ ССЫЛКА Справочник.ДоговорыКонтрагентов"""):
        pay[(s(r["Орг"]), s(r["Кт"]))][s(r["Дог"])] = r["Дог"]
    for r in q("""ВЫБРАТЬ Д.Организация КАК Орг, Д.Контрагент КАК Кт, Д.Ссылка КАК Дог ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ НЕ Д.ПометкаУдаления"""):
        cat[(s(r["Орг"]), s(r["Кт"]))][s(r["Дог"])] = r["Дог"]
    ok = skip = 0
    for r in hang:
        k = (s(r["Орг"]), s(r["Кт"]))
        c = pay.get(k) if len(pay.get(k, {})) == 1 else (cat.get(k) if not pay.get(k) and len(cat.get(k, {})) == 1 else None)
        if not c:
            skip += 1; print("ПРОПУСК (нет однозначного договора)", s(r["Док"])[-45:], k[1][:40]); continue
        dog = list(c.values())[0]; o = r["Док"].ПолучитьОбъект()
        for i in range(o.РасшифровкаПлатежа.Количество()):
            row = o.РасшифровкаПлатежа.Получить(i)
            if "Поступление безналичных" in s(row.Заказ): row.Заказ = dog
        tag(o)
        try:
            o.Записать(ib.РежимЗаписиДокумента.Проведение); ok += 1
            log(f"21-15б поступление привязано к договору: {s(r['Док'])} -> {s(dog)[:60]}")
        except Exception as e: print("ОШИБКА", s(r["Док"])[-45:], str(e)[-150:])
    print(f"поступления: исправлено {ok}, пропущено {skip}")

if "а" in STEPS:
    rows = q("""ВЫБРАТЬ Д.Ссылка КАК Д ИЗ Документ.ЗаказПоставщику КАК Д ГДЕ Д.Проведен И Д.Дата < &Д60
      И Д.Статус <> ЗНАЧЕНИЕ(Перечисление.СтатусыЗаказовПоставщикам.Закрыт) УПОРЯДОЧИТЬ ПО Д.Дата""", Д60=D60)
    ok = 0
    for r in rows:
        o = r["Д"].ПолучитьОбъект(); o.Статус = ib.Перечисления.СтатусыЗаказовПоставщикам.Закрыт; tag(o)
        d0 = o.Дата
        # пустые даты поступления (из-за них «Период не может быть пустым») -> дата заказа
        empty = lambda v: getattr(v, "year", 9999) < 1900
        if empty(o.ДатаПоступления):
            o.ДатаПоступления = d0
        if empty(o.ЖелаемаяДатаПоступления):
            o.ЖелаемаяДатаПоступления = d0
        for i in range(o.Товары.Количество()):
            row = o.Товары.Получить(i)
            if empty(row.ДатаПоступления):
                row.ДатаПоступления = o.ДатаПоступления
        try: o.Записать(ib.РежимЗаписиДокумента.Проведение); ok += 1
        except Exception as e: print("ОШИБКА", s(r["Д"])[-45:], str(e)[-150:])
    log(f"21-15а заказы поставщикам старше 60 дн. закрыты: {ok} из {len(rows)}")

if "к" in STEPS:
    rows = q("""ВЫБРАТЬ Д.Ссылка КАК Д ИЗ Документ.ЗаказКлиента КАК Д ГДЕ Д.Проведен И Д.Дата < &Д60
      И Д.Статус = ЗНАЧЕНИЕ(Перечисление.СтатусыЗаказовКлиентов.НеСогласован) УПОРЯДОЧИТЬ ПО Д.Дата""", Д60=D60)
    ok = 0
    for r in rows:
        o = r["Д"].ПолучитьОбъект(); o.Статус = ib.Перечисления.СтатусыЗаказовКлиентов.Закрыт; tag(o)
        o.ОбменДанными.Загрузка = True
        try:
            o.Записать(); ok += 1
            if ok % 500 == 0: print("  ...", ok)
        except Exception as e: print("ОШИБКА", s(r["Д"])[-45:], str(e)[-150:])
    log(f"21-15а2 заказы клиентов «На согласовании» старше 60 дн. закрыты: {ok} из {len(rows)}")
