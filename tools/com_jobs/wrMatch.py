# Чтение: «списали (недостача / внутреннее потребление / производство) → позже оприходовали излишком» — FIFO по ТОВАРУ по всем складам (учёт перемещений), окно 12 мес.
from collections import defaultdict
OUTT = {"Списание недостач товаров": "СписНед", "Внутреннее потребление товаров": "ВнПотр", "Производство без заказа": "Произв"}
rows = q("""ВЫБРАТЬ Т.Период КАК П, Т.Регистратор КАК Р, ТИПЗНАЧЕНИЯ(Т.Регистратор) КАК ТР, Т.АналитикаУчетаНоменклатуры.Номенклатура КАК Н, Т.АналитикаУчетаНоменклатуры.Склад КАК С,
  Т.ВидДвижения КАК ВД, СУММА(Т.Количество) КАК К
ИЗ РегистрНакопления.ТоварыОрганизаций КАК Т
ГДЕ Т.Активность И Т.Период >= &Н И (Т.Регистратор ССЫЛКА Документ.СписаниеНедостачТоваров ИЛИ Т.Регистратор ССЫЛКА Документ.ВнутреннееПотреблениеТоваров
   ИЛИ Т.Регистратор ССЫЛКА Документ.ПроизводствоБезЗаказа ИЛИ Т.Регистратор ССЫЛКА Документ.ОприходованиеИзлишковТоваров)
СГРУППИРОВАТЬ ПО Т.Период, Т.Регистратор, ТИПЗНАЧЕНИЯ(Т.Регистратор), Т.АналитикаУчетаНоменклатуры.Номенклатура, Т.АналитикаУчетаНоменклатуры.Склад, Т.ВидДвижения
УПОРЯДОЧИТЬ ПО Т.Период""", Н=datetime.datetime(2025, 1, 1))
outs = defaultdict(list); MATCH = []
for r in rows:
    k = s(r["Н"]); t = s(r["ТР"]); prih = "Приход" in s(r["ВД"])
    if not prih and t in OUTT:
        outs[k].append([r, r["К"]])
    elif prih and t.startswith("Оприходование излишков"):
        need = r["К"]
        for o in outs[k]:
            if need <= 0.0005:
                break
            od = o[0]["П"]; rd = r["П"]
            if o[1] <= 0.0005 or (rd.year * 12 + rd.month) - (od.year * 12 + od.month) > 12:
                continue
            m = min(o[1], need); o[1] -= m; need -= m
            MATCH.append((OUTT[s(o[0]["ТР"])], o[0], r, m, k))
by = defaultdict(lambda: [0, 0.0, set(), set()])
for t, o, r, m, k in MATCH:
    b = by[t]; b[0] += 1; b[1] += m; b[2].add(s(r["Р"])); b[3].add(s(o["Р"]))
rin = sum(r["К"] for r in rows if "Приход" in s(r["ВД"]) and s(r["ТР"]).startswith("Оприходование"))
print(f"оприходовано излишками всего {rin:,.2f}; из них покрыто прежними списаниями того же товара: {sum(x[3] for x in MATCH):,.2f}")
for t, (n, qy, rd, od) in by.items():
    print(f"  {t:>8} → Оприх. излишков: пар {n}, кол-во {qy:,.2f}, оприх.док {len(rd)}, док-списаний {len(od)}")
tot = defaultdict(float)
for t, o, r, m, k in MATCH:
    tot[(t, k)] += m
print("== топ-20 товаров")
for (t, k), v in sorted(tot.items(), key=lambda x: -x[1])[:20]:
    print(f"  {t:>8} | {k[:50]:<50} | {v:,.2f}")
