# 22-И (чтение, копия ANESCOM на 22.10.2026): склад «Ламинация Автокомп» и связь с АВТОКОМП.
# 1) обороты склада по видам документов и годам; 2) остатки на 22.10.2026 по товарам; 3) куда уходило со склада (перемещения — склад-получатель);
# 4) закупки ANESCOM у АВТОКОМП (приобретения, контрагент АВТОКОМП) по годам и видам товаров (ламинированный профиль / прочее).
from collections import defaultdict
N, K = datetime.datetime(2024, 1, 1), datetime.datetime(2026, 12, 31, 23, 59, 59)
sk = q("""ВЫБРАТЬ С.Ссылка КАК С, С.Наименование КАК Н ИЗ Справочник.Склады КАК С ГДЕ С.Наименование ПОДОБНО "%Ламинац%" ИЛИ С.Наименование ПОДОБНО "%Автокомп%" ИЛИ С.Наименование ПОДОБНО "%АВТОКОМП%" """)
print("== Склады:", [s(r["Н"]) for r in sk])
for r0 in sk:
    S = r0["С"]; print(f"\n######## {s(S)}")
    print("== Обороты по видам документов (приход / расход, шт)")
    for r in q("""ВЫБРАТЬ ТИПЗНАЧЕНИЯ(Т.Регистратор) КАК Т, ГОД(Т.Период) КАК Г, СУММА(Т.ВНаличииПриход) КАК П, СУММА(Т.ВНаличииРасход) КАК Р
    ИЗ РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты(&Н, &К, Регистратор, , Склад = &С) КАК Т
    СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(Т.Регистратор), ГОД(Т.Период) УПОРЯДОЧИТЬ ПО Г""", Н=N, К=K, С=S):
        print(f"  {r['Г']} | {s(r['Т'])[:40]} | приход {float(r['П'] or 0):,.1f} | расход {float(r['Р'] or 0):,.1f}")
    rows = q("""ВЫБРАТЬ Т.Номенклатура КАК Н, Т.ВНаличииКонечныйОстаток КАК О, Т.ВНаличииПриход КАК П, Т.ВНаличииРасход КАК Р
    ИЗ РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты(&Н, &К, , , Склад = &С) КАК Т""", Н=N, К=K, С=S)
    print(f"== Остаток на конец, позиций {len([1 for r in rows if abs(float(r['О'] or 0))>0.001])}, шт {sum(float(r['О'] or 0) for r in rows):,.1f}; приход {sum(float(r['П'] or 0) for r in rows):,.1f}; расход {sum(float(r['Р'] or 0) for r in rows):,.1f}")
    for r in sorted(rows, key=lambda r: -abs(float(r["О"] or 0)))[:25]:
        print(f"   {s(r['Н'])[:60]} | ост {float(r['О'] or 0):,.1f} | +{float(r['П'] or 0):,.1f} −{float(r['Р'] or 0):,.1f}")
    print("== Перемещения со склада: куда (шт)")
    try:
        for r in q("""ВЫБРАТЬ Д.Ссылка.СкладПолучатель КАК П, ГОД(Д.Ссылка.Дата) КАК Г, СУММА(Д.Количество) КАК К, КОЛИЧЕСТВО(РАЗЛИЧНЫЕ Д.Ссылка) КАК Н
        ИЗ Документ.ПеремещениеТоваров.Товары КАК Д ГДЕ Д.Ссылка.Проведен И Д.Ссылка.СкладОтправитель = &С И Д.Ссылка.Дата МЕЖДУ &Н И &К
        СГРУППИРОВАТЬ ПО Д.Ссылка.СкладПолучатель, ГОД(Д.Ссылка.Дата)""", Н=N, К=K, С=S):
            print(f"  {r['Г']} → {s(r['П'])[:40]} | док {r['Н']} | шт {float(r['К'] or 0):,.1f}")
    except Exception as e: print("  перемещения:", str(e)[-120:])
print("\n== Приобретения ANESCOM у АВТОКОМП по годам (шт / сумма млн): ламинированный профиль (Helios/Bauline/Standart/АК-) и прочее")
try:
    agg = defaultdict(lambda: [0.0, 0.0])
    for r in q("""ВЫБРАТЬ ГОД(Д.Ссылка.Дата) КАК Г, Д.Номенклатура.Наименование КАК Н, СУММА(Д.Количество) КАК К, СУММА(Д.Сумма) КАК С
    ИЗ Документ.ПриобретениеТоваровУслуг.Товары КАК Д ГДЕ Д.Ссылка.Проведен И Д.Ссылка.Контрагент.Наименование ПОДОБНО "%АВТОКОМП%" И Д.Ссылка.Дата МЕЖДУ &Н И &К
    СГРУППИРОВАТЬ ПО ГОД(Д.Ссылка.Дата), Д.Номенклатура.Наименование""", Н=N, К=K):
        n = s(r["Н"]); g = "ламинир." if any(w in n for w in ("Helios", "Bauline", "Standart", "АК-", "AK-", "Темный дуб", "Антрацит")) else "прочее"
        a = agg[(r["Г"], g)]; a[0] += float(r["К"] or 0); a[1] += float(r["С"] or 0)
    for (g, t), (k, sm) in sorted(agg.items()): print(f"  {g} | {t} | шт {k:,.1f} | {sm/1e6:,.2f} млн")
except Exception as e: print("  приобретения:", str(e)[-150:])
