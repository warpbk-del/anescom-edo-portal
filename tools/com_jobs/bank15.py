# (чтение) образцы vs копии: движения по регистрам и реквизиты основания
def info(num):
    r = q('ВЫБРАТЬ Д.Ссылка КАК С ИЗ Документ.ПоступлениеБезналичныхДенежныхСредств КАК Д ГДЕ Д.Номер = &Н И ГОД(Д.Дата) = 2026', Н=num)[0]['С']
    o = r.ПолучитьОбъект(); m = o.Метаданные()
    hdr = {m.Реквизиты.Получить(i).Имя: s(getattr(o, m.Реквизиты.Получить(i).Имя))[:40] for i in range(m.Реквизиты.Количество()) if any(w in m.Реквизиты.Получить(i).Имя for w in ('Основ', 'Касс', 'Эквайр', 'Операц', 'ПоДокумент', 'Терминал', 'Инкасс'))}
    rows = [{c: s(getattr(o.РасшифровкаПлатежа.Получить(j), c))[:30] for c in ('Заказ', 'ДокументОснование', 'Сумма', 'ЭквайринговыйТерминал', 'ОснованиеПлатежа') if hasattr(o.РасшифровкаПлатежа.Получить(j), c)} for j in range(o.РасшифровкаПлатежа.Количество())]
    regs = {}
    for k in range(r.Метаданные().Движения.Количество()):
        rg = r.Метаданные().Движения.Получить(k); nm = rg.ПолноеИмя()
        try:
            n = q(f'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ {nm} КАК Т ГДЕ Т.Регистратор = &Р', Р=r)[0]['К']
            if n: regs[nm.split('.')[-1]] = n
        except Exception: pass
    print(num, '| шапка', hdr, '\n   ТЧ', rows[:3], '\n   движения', regs)
for n in ('00НФ-002821', '00НФ-002828', '00НФ-002815', '00НФ-002831', '00НФ-002799', '00НФ-002830'): info(n)
