rest = [(s(r["С1"]), s(r["Орг"]), float(r["Ост"])) for r in rows_3350(D) if float(r["Ост"]) > 0.009]
used = {}
for dr, kr, amt in pl: used[(s(dr["С1"]), s(dr["Орг"]))] = used.get((s(dr["С1"]), s(dr["Орг"])), 0) + amt
left = [(n, o, round(v - used.get((n, o), 0), 2)) for n, o, v in rest if v - used.get((n, o), 0) > 0.009]
print(f"== Останется переплат (Дт 3350) после зачёта: {len(left)}, {sum(x[2] for x in left):,.2f}")
