# По сотруднику на min(Дт-сальдо в орг. A, Кт-сальдо в орг. B):
#   в орг. A (переплата): Дт 1240 (субконто — орг. B)  Кт 3350 (сотрудник)
#   в орг. B (долг):      Дт 3350 (сотрудник)          Кт 3340 (субконто — орг. A)
