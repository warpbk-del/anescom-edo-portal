D2 = datetime.datetime(2026, 10, 1, 6)
pl2 = plan(D2)
print(f"== ПОВТОРЯЕТСЯ ЛИ: на 30.09.2026 перекос между организациями {sum(x[2] for x in pl2):,.2f} ({len({s(x[0]['С1']) for x in pl2})} сотр.)")
print("== Выплаты ЗП 07.2025–09.2026 из одной организации при начислении в другой (по месяцам, сумма Дт3350 по организации ≠ Кт3350)")
