# (чтение) Детали для GREENTE: статьи в документах без счетов и как такие же статьи отражены у ANESCOM.
import collections
def docby(kind, num):
    r = q(f'ВЫБРАТЬ Д.Ссылка КАК С ИЗ Документ.{kind} КАК Д ГДЕ Д.Номер = &Н', Н=num)
    return r[0]['С'] if r else None
for kind, num in (('ПоступлениеБезналичныхДенежныхСредств', 'GTНФ-000013'), ('СписаниеБезналичныхДенежныхСредств', 'GTНФ-000014')):
    d = docby(kind, num)
    if d is None: print('нет', num); continue
    print('DOC', s(d), '| операция', s(d.ХозяйственнаяОперация), '| подразделение', s(d.Подразделение) if hasattr(d, 'Подразделение') else '-')
    tc = d.РасшифровкаПлатежа
    for i in range(min(tc.Количество(), 3)):
        r = tc.Получить(i); vals = []
        for f in ('СтатьяРасходов', 'СтатьяАктивовПассивов', 'СтатьяДвиженияДенежныхСредств', 'АналитикаРасходов', 'АналитикаАктивовПассивов', 'Сумма'):
            try: vals.append(f'{f}={s(getattr(r, f))[:40]}')
            except Exception: pass
        print('   строка', i + 1, vals)
        for f in ('СтатьяРасходов', 'СтатьяАктивовПассивов'):
            try:
                st = getattr(r, f)
                if st is None or not s(st): continue
                m = st.Метаданные()
                accs = [f'{m.Реквизиты.Получить(j).Имя}={s(getattr(st, m.Реквизиты.Получить(j).Имя))}' for j in range(m.Реквизиты.Количество()) if 'Счет' in m.Реквизиты.Получить(j).Имя]
                print('     статья', s(st), accs)
                # как отражена эта статья у ANESCOM: проводки документов с этой статьёй
                c = collections.Counter()
                for x in q(f'ВЫБРАТЬ ПЕРВЫЕ 2000 Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт ИЗ РегистрБухгалтерии.{{REG}} КАК Х ГДЕ Х.Регистратор В (ВЫБРАТЬ Т.Ссылка ИЗ Документ.{kind}.РасшифровкаПлатежа КАК Т ГДЕ Т.{f} = &С И НЕ Т.Ссылка.Организация.Префикс = "GT")', С=st):
                    c[(x['Дт'], x['Кт'])] += 1
                print('     у ANESCOM проводки:', c.most_common(5))
            except Exception as e: print('     ERR', f, str(e)[-100:])
