# 21-14: приобретения/реализации «по накладным», у которых договор «по договорам» -> порядок расчётов «по договорам», перепровести.
# Тогда долг ложится на договор и закрывается оплатами по этому договору. DRY=True (по умолчанию) — только подсчёт.
DRY = globals().get("DRY", True)
res = {}
for doc in ("ПриобретениеТоваровУслуг", "РеализацияТоваровУслуг"):
    rows = q(f"""ВЫБРАТЬ Д.Ссылка КАК Д, Д.Дата КАК Дата, Д.СуммаДокумента КАК С, Д.Договор.ПорядокРасчетов КАК ПД
    ИЗ Документ.{doc} КАК Д
    ГДЕ Д.Проведен И Д.ПорядокРасчетов = ЗНАЧЕНИЕ(Перечисление.ПорядокРасчетов.ПоНакладным)
    УПОРЯДОЧИТЬ ПО Д.Дата""")
    grp = {}
    for r in rows:
        k = s(r["ПД"]) or "(нет договора)"; g = grp.setdefault(k, [0, 0.0]); g[0] += 1; g[1] += float(r["С"] or 0)
    print(doc, "по накладным:", len(rows), {k: (v[0], f"{v[1]:,.0f}") for k, v in grp.items()})
    todo = [r for r in rows if s(r["ПД"]) == s(ib.Перечисления.ПорядокРасчетов.ПоДоговорамКонтрагентов)]
    print("   к исправлению (договор «по договорам»):", len(todo), "с", s(todo[0]["Дата"])[:10] if todo else "-")
    if DRY:
        continue
    ok = err = 0
    for r in todo:
        o = r["Д"].ПолучитьОбъект()
        o.ПорядокРасчетов = ib.Перечисления.ПорядокРасчетов.ПоДоговорамКонтрагентов
        if "[аудит 24.10.2026]" not in o.Комментарий:
            o.Комментарий = (o.Комментарий + " [аудит 24.10.2026]").strip()
        try:
            o.Записать(ib.РежимЗаписиДокумента.Проведение); ok += 1
            if ok % 100 == 0: print("   ...", ok)
        except Exception as e:
            err += 1; print("ОШИБКА", s(r["Д"])[-45:], str(e)[-150:])
    log(f"21-14 {doc}: порядок расчётов «по накладным» -> «по договорам» и перепроведено {ok}, ошибок {err}")
