# Чтение: если убрать «Корректировки регистров» из ТоварыОрганизаций — совпадут ли ведомости склад/организация?
from collections import defaultdict
D = datetime.datetime(2026, 10, 31, 23, 59, 59)
A = q("""ВЫБРАТЬ Т.Номенклатура КАК Н, Т.Склад КАК С, СУММА(Т.ВНаличииОстаток) КАК К ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(&Д, ) КАК Т СГРУППИРОВАТЬ ПО Т.Номенклатура, Т.Склад""", Д=D)
B = q("""ВЫБРАТЬ Т.АналитикаУчетаНоменклатуры.Номенклатура КАК Н, Т.АналитикаУчетаНоменклатуры.Склад КАК С, СУММА(Т.КоличествоОстаток) КАК К
ИЗ РегистрНакопления.ТоварыОрганизаций.Остатки(&Д, ) КАК Т СГРУППИРОВАТЬ ПО Т.АналитикаУчетаНоменклатуры.Номенклатура, Т.АналитикаУчетаНоменклатуры.Склад""", Д=D)
K = q("""ВЫБРАТЬ Т.АналитикаУчетаНоменклатуры.Номенклатура КАК Н, Т.АналитикаУчетаНоменклатуры.Склад КАК С,
  СУММА(ВЫБОР КОГДА Т.ВидДвижения = ЗНАЧЕНИЕ(ВидДвиженияНакопления.Приход) ТОГДА Т.Количество ИНАЧЕ -Т.Количество КОНЕЦ) КАК К
ИЗ РегистрНакопления.ТоварыОрганизаций КАК Т ГДЕ Т.Регистратор ССЫЛКА Документ.КорректировкаРегистров И Т.Активность
СГРУППИРОВАТЬ ПО Т.АналитикаУчетаНоменклатуры.Номенклатура, Т.АналитикаУчетаНоменклатуры.Склад""")
m = defaultdict(lambda: [0.0, 0.0, 0.0])
for r in A: m[(s(r["Н"]), s(r["С"]))][0] += r["К"] or 0
for r in B: m[(s(r["Н"]), s(r["С"]))][1] += r["К"] or 0
for r in K: m[(s(r["Н"]), s(r["С"]))][2] += r["К"] or 0
before = sum(1 for v in m.values() if abs(v[0] - v[1]) > 0.0005)
after = [(k, v) for k, v in m.items() if abs(v[0] - (v[1] - v[2])) > 0.0005]
print(f"расхождений сейчас: {before}; без «Корректировок регистров»: {len(after)}; строк корректировок по товарам: {len(K)}")
for k, v in sorted(after, key=lambda x: -abs(x[1][0] - x[1][1] + x[1][2]))[:20]:
    print(f"  {k[1][:20]:<20} | {k[0][:40]:<40} | скл {v[0]:>9.2f} орг-без-корр {v[1]-v[2]:>9.2f}")
