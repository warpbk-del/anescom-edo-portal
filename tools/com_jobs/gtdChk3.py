# (чтение) 3232 полностью (кратко) и ГЕЦЕ ГмбХ 3310: хвост после последнего нуля, с валютной суммой
W = globals().get('WHAT', '3232')
if W == '3232':
    b = 0
    for r in q('ВЫБРАТЬ Х.Регистратор КАК Р, МИНИМУМ(Х.Период) КАК П, СУММА(ВЫБОР КОГДА Х.СчетДт.Код = "3232" ТОГДА Х.Сумма ИНАЧЕ -Х.Сумма КОНЕЦ) КАК С ИЗ РегистрБухгалтерии.{REG} КАК Х ГДЕ Х.Организация.Наименование ПОДОБНО "%ANESCOM%" И (Х.СчетДт.Код = "3232" ИЛИ Х.СчетКт.Код = "3232") И НЕ (Х.СчетДт.Код = "3232" И Х.СчетКт.Код = "3232") СГРУППИРОВАТЬ ПО Х.Регистратор УПОРЯДОЧИТЬ ПО П'):
        b += float(r['С']); print(' ', str(r['П'])[:10], f"{float(r['С']):>14,.2f}", f"сальдо {b:>12,.2f}", s(r['Р'])[:50])
else:
    R = []
    for r in q('ВЫБРАТЬ Х.Регистратор КАК Р, Х.Период КАК П, Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт, Х.Сумма КАК С, Х.ВалютнаяСуммаДт КАК ВД, Х.ВалютнаяСуммаКт КАК ВК, Х.СубконтоДт1 КАК СД, Х.СубконтоКт1 КАК СК ИЗ РегистрБухгалтерии.{REG}.ДвиженияССубконто(, , Организация.Наименование ПОДОБНО "%ANESCOM%" И (СчетДт.Код = "3310" ИЛИ СчетКт.Код = "3310"), , ) КАК Х УПОРЯДОЧИТЬ ПО Х.Период'):
        dt = r['Дт'] == '3310'; k = s(r['СД'] if dt else r['СК']).upper()
        if 'ГЕЦЕ' not in k or 'GMBH' not in k.replace('ГМБХ', 'GMBH'): continue
        sg = 1 if dt else -1
        R.append((str(r['П'])[:10], sg * float(r['С']), sg * float((r['ВД'] if dt else r['ВК']) or 0), s(r['Р'])[:45]))
    bal = 0; cur = 0; last0 = 0
    for i, x in enumerate(R):
        bal += x[1]; cur += x[2]
        if abs(cur) < 1: last0 = i + 1
    print('итого KZT', f'{bal:,.2f}', 'валюта', f'{cur:,.2f}', 'строк', len(R), 'после последнего нуля в валюте:', len(R) - last0)
    b = c = 0
    for x in R[:last0]: b += x[1]; c += x[2]
    for x in R[last0:]:
        b += x[1]; c += x[2]
        if 'курсов' in x[3].lower() or 'Регламентная' in x[3]: continue
        print(' ', x[0], f'{x[1]:>14,.2f}', f'вал {x[2]:>12,.2f}', f'| сальдо {b:>14,.2f} / {c:>12,.2f}', x[3])
