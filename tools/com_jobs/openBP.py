# Чтение: остатки БП на 31.12.2024 (конец дня) по счетам с субконто — для довнесения в КА.
ACCS = globals().get("OPEN_ACCS", ("3381", "3360", "3350", "1030", "1010"))
z = ib_bp.NewObject("Запрос")
z.Текст = """ВЫБРАТЬ Т.Счет.Код КАК С, Т.Организация КАК О, Т.Субконто1 КАК С1, Т.Субконто2 КАК С2, Т.СуммаОстатокДт - Т.СуммаОстатокКт КАК Б
ИЗ РегистрБухгалтерии.Хозрасчетный.Остатки(&Д, , , ) КАК Т"""
z.УстановитьПараметр("Д", datetime.datetime(2025, 1, 1, 5, 0, 0))
sel = z.Выполнить().Выбрать()
BPBAL = []
while sel.Следующий():
    if sel.С in ACCS and abs(sel.Б or 0) > 0.005:
        BPBAL.append((sel.С, ib_bp.String(sel.О), ib_bp.String(sel.С1), ib_bp.String(sel.С2), sel.Б))
for a in ACCS:
    rs = [x for x in BPBAL if x[0] == a]
    print(f"== БП {a}: строк {len(rs)}, итого {sum(x[4] for x in rs):,.2f}")
    for x in sorted(rs, key=lambda x: x[4])[:15]:
        print(f"    {x[1][:18]:<18} | {x[2][:40]:<40} | {x[3][:28]:<28} | {x[4]:>15,.2f}")
