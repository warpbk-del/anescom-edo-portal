# Перемещения аудита: статус «Принято» (иначе товар не приходует на склад получателя), перепровести.
docs = q("""ВЫБРАТЬ Д.Ссылка КАК Д ИЗ Документ.ПеремещениеТоваров КАК Д ГДЕ Д.Комментарий ПОДОБНО "%аудит 24.10.2026%" И НЕ Д.ПометкаУдаления""")
st = ib.Перечисления.СтатусыПеремещенийТоваров.Принято
ok = er = 0
for r in docs:
    try:
        o = r["Д"].ПолучитьОбъект(); o.Статус = st; o.Записать(ib.РежимЗаписиДокумента.Проведение); ok += 1
    except Exception as e:
        er += 1; print("ОШИБКА", s(r["Д"])[-40:], str(e)[-150:])
log(f"21-9b перемещения аудита → «Принято»: {ok}, ошибок {er}")
