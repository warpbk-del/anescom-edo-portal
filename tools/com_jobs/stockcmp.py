# Сверка: Ведомость по товарам на складах (ТоварыНаСкладах.ВНаличии) vs Ведомость по товарам организаций (ТоварыОрганизаций.Количество)
# Сравнение по Номенклатура + Характеристика + Склад на дату D (по умолчанию — текущая). CSV: D:\anescom_edo\data\reports\stock_cmp.csv
import csv
from collections import defaultdict
D = globals().get("D_STOCK") or datetime.datetime(2026, 10, 31, 23, 59, 59)
A = q("""ВЫБРАТЬ Т.Номенклатура КАК Н, Т.Характеристика КАК Х, Т.Склад КАК С, СУММА(Т.ВНаличииОстаток) КАК К
ИЗ РегистрНакопления.ТоварыНаСкладах.Остатки(&Д, ) КАК Т СГРУППИРОВАТЬ ПО Т.Номенклатура, Т.Характеристика, Т.Склад""", Д=D)
B = q("""ВЫБРАТЬ Т.АналитикаУчетаНоменклатуры.Номенклатура КАК Н, Т.АналитикаУчетаНоменклатуры.Характеристика КАК Х, Т.АналитикаУчетаНоменклатуры.Склад КАК С,
  ТИПЗНАЧЕНИЯ(Т.АналитикаУчетаНоменклатуры.Склад) КАК ТС, СУММА(Т.КоличествоОстаток) КАК К
ИЗ РегистрНакопления.ТоварыОрганизаций.Остатки(&Д, ) КАК Т
СГРУППИРОВАТЬ ПО Т.АналитикаУчетаНоменклатуры.Номенклатура, Т.АналитикаУчетаНоменклатуры.Характеристика, Т.АналитикаУчетаНоменклатуры.Склад, ТИПЗНАЧЕНИЯ(Т.АналитикаУчетаНоменклатуры.Склад)""", Д=D)
print("строк: склады", len(A), "| организации", len(B))
m = defaultdict(lambda: [0.0, 0.0, "", "", ""])
for r in A:
    k = (s(r["Н"]), s(r["Х"]), s(r["С"])); x = m[k]; x[0] += r["К"] or 0; x[2:] = [s(r["Н"]), s(r["Х"]), s(r["С"])]
nonwh = defaultdict(float)
for r in B:
    k = (s(r["Н"]), s(r["Х"]), s(r["С"])); x = m[k]; x[1] += r["К"] or 0; x[2:] = [s(r["Н"]), s(r["Х"]), s(r["С"])]
    t = s(r["ТС"])
    if "Склад" not in t:
        nonwh[t] += r["К"] or 0
diff = {k: v for k, v in m.items() if abs(v[0] - v[1]) > 0.0005}
print("позиций всего", len(m), "| расхождений", len(diff))
print("Не склады в ТоварыОрганизаций (у переработчика/комиссионера и т.п.):", {k: round(v, 2) for k, v in nonwh.items()})
bywh = defaultdict(lambda: [0, 0.0, 0.0])
for k, v in diff.items():
    w = bywh[k[2]]; w[0] += 1; w[1] += v[0] - v[1]; w[2] += abs(v[0] - v[1])
print("== по складам: расхождений | сумма (склад−орг) | сумма модулей")
for w, v in sorted(bywh.items(), key=lambda x: -x[1][2])[:25]:
    print(f"  {w[:45]:<45} {v[0]:>5} {v[1]:>12.2f} {v[2]:>12.2f}")
print("== топ-25 позиций")
for k, v in sorted(diff.items(), key=lambda x: -abs(x[1][0] - x[1][1]))[:25]:
    print(f"  {k[2][:22]:<22} | {k[0][:45]:<45} | {k[1][:15]:<15} | склад {v[0]:>10.3f} орг {v[1]:>10.3f} разн {v[0]-v[1]:>10.3f}")
with open(r"D:\anescom_edo\data\reports\stock_cmp.csv", "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["Склад", "Номенклатура", "Характеристика", "На складах", "Организаций", "Разница"])
    for k, v in sorted(diff.items()):
        w.writerow([k[2], k[0], k[1], round(v[0], 3), round(v[1], 3), round(v[0] - v[1], 3)])
print("CSV записан")
