# Чтение: какие документы двигают ТоварыОрганизаций в 2025–2026 (приход/расход, кол-во документов, количество)
from collections import defaultdict
agg = defaultdict(lambda: [0.0, 0.0, set()])
for r in q("""ВЫБРАТЬ ТИПЗНАЧЕНИЯ(Т.Регистратор) КАК ТР, Т.Регистратор КАК Р, Т.ВидДвижения КАК В, СУММА(Т.Количество) КАК К
ИЗ РегистрНакопления.ТоварыОрганизаций КАК Т ГДЕ Т.Активность И Т.Период >= &Н СГРУППИРОВАТЬ ПО ТИПЗНАЧЕНИЯ(Т.Регистратор), Т.Регистратор, Т.ВидДвижения""",
           Н=datetime.datetime(2025, 1, 1)):
    a = agg[s(r["ТР"])]
    if "Приход" in s(r["В"]):
        a[0] += r["К"]
    else:
        a[1] += r["К"]
    a[2].add(s(r["Р"]))
for t, (i, o, d) in sorted(agg.items(), key=lambda x: -len(x[1][2])):
    print(f"  {t[:55]:<55} док {len(d):>6}  приход {i:>14,.1f}  расход {o:>14,.1f}")
