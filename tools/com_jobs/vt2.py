import collections
p = [x for x in P if 'Витраж' in x['Н']][0]['С']
keys = q('ВЫБРАТЬ А.КлючАналитики КАК К ИЗ РегистрСведений.АналитикаУчетаНоменклатуры КАК А ГДЕ А.Склад = &П', П=p)
a = ib.NewObject('Массив')
for k in keys: a.Добавить(k['К'])
T = ib.НайтиПоСсылкам(a)
c = collections.Counter(); ks = set()
for i in range(T.Количество()):
    r = T.Получить(i); fn = r.Метаданные.ПолноеИмя()
    if fn in ('РегистрСведений.АналитикаУчетаНоменклатуры', 'Справочник.КлючиАналитикиУчетаНоменклатуры'): continue
    c[fn] += 1; ks.add(ib.XMLСтрока(r.Ссылка))
print('KEYS', len(keys), '| ключей с движениями/ссылками', len(ks))
for k, v in c.most_common(): print(f'  {v:5d} {k}')
