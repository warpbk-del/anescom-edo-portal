# (Производство без заказа, 2025–2026) значениями самой частой комбинации в документе, перепровести.
from collections import Counter
docs = q("""ВЫБРАТЬ РАЗЛИЧНЫЕ Д.Ссылка КАК Д ИЗ Документ.ПроизводствоБезЗаказа.МатериалыИРаботы КАК Д
ГДЕ Д.Ссылка.Проведен И Д.Ссылка.Дата >= &Н
 И (Д.СтатьяКалькуляции = ЗНАЧЕНИЕ(Справочник.СтатьиКалькуляции.ПустаяСсылка) ИЛИ Д.НомерГруппыЗатрат = 0)
УПОРЯДОЧИТЬ ПО Д.Ссылка.Дата""", Н=datetime.datetime(2025, 1, 1))
print("документов с пустыми строками:", len(docs))
F = ("НомерГруппыЗатрат", "СтатьяКалькуляции", "АналитикаУчетаПартийПроизводства")
bad = 0
for r in docs:
    o = r["Д"].ПолучитьОбъект(); tp = o.МатериалыИРаботы
    combos = Counter(); first = {}
    for i in range(tp.Количество()):
        row = tp.Получить(i)
        if row.НомерГруппыЗатрат and s(row.СтатьяКалькуляции):
            k = tuple(s(getattr(row, f)) for f in F); combos[k] += 1; first.setdefault(k, i)
    if not combos:
        print("НЕТ ОБРАЗЦА", s(r["Д"])); bad += 1; continue
    src = tp.Получить(first[combos.most_common(1)[0][0]])
    fixed = 0
    for i in range(tp.Количество()):
        row = tp.Получить(i)
        if not row.НомерГруппыЗатрат or not s(row.СтатьяКалькуляции):
            for f in F:
                setattr(row, f, getattr(src, f))
            fixed += 1
    try:
        o.Записать(ib.РежимЗаписиДокумента.Проведение)
        log(f"21-12 дозаполнено строк {fixed} ({' / '.join(combos.most_common(1)[0][0][1:])}), перепроведён {s(r['Д'])}")
    except Exception as e:
        bad += 1; print("ОШИБКА", s(r["Д"])[-45:], str(e)[-150:])
print("итого документов", len(docs), "ошибок", bad)
