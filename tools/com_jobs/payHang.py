from collections import defaultdict
hang = q("""ВЫБРАТЬ Д.Ссылка КАК Док, Д.Ссылка.Дата КАК Дата, Д.Ссылка.Номер КАК Номер, Д.Ссылка.Организация КАК Орг,
 Д.Ссылка.Контрагент КАК Кт, Д.Партнер КАК Партнер, Д.Сумма КАК Сумма, Д.Ссылка.НазначениеПлатежа КАК Назн
ИЗ Документ.СписаниеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК Д
ГДЕ Д.Ссылка.Проведен И Д.Ссылка.Дата >= &Н И Д.Ссылка.ХозяйственнаяОперация = ЗНАЧЕНИЕ(Перечисление.ХозяйственныеОперации.ОплатаПоставщику)
 И Д.Заказ ССЫЛКА Документ.СписаниеБезналичныхДенежныхСредств
УПОРЯДОЧИТЬ ПО Д.Ссылка.Дата""", Н=datetime.datetime(2025, 1, 1))
dg = q("""ВЫБРАТЬ Д.Ссылка.Организация КАК Орг, Д.Ссылка.Контрагент КАК Кт, Д.Заказ КАК Дог, КОЛИЧЕСТВО(*) КАК Н, МАКСИМУМ(Д.Ссылка.Дата) КАК Посл
ИЗ Документ.СписаниеБезналичныхДенежныхСредств.РасшифровкаПлатежа КАК Д
ГДЕ Д.Ссылка.Проведен И Д.Заказ ССЫЛКА Справочник.ДоговорыКонтрагентов
СГРУППИРОВАТЬ ПО Д.Ссылка.Организация, Д.Ссылка.Контрагент, Д.Заказ""")
cand = defaultdict(list)
for r in dg:
    cand[(s(r["Орг"]), s(r["Кт"]))].append((r["Н"], s(r["Дог"]), s(r["Посл"])[:10]))
allc = q("""ВЫБРАТЬ Д.Организация КАК Орг, Д.Контрагент КАК Кт, Д.Ссылка КАК Дог ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ НЕ Д.ПометкаУдаления""")
anyc = defaultdict(list)
for r in allc:
    anyc[(s(r["Орг"]), s(r["Кт"]))].append(s(r["Дог"]))
out = r"D:\anescom_edo\data\reports\21-13_висящие_оплаты_поставщикам.csv"
stat = defaultdict(lambda: [0, 0.0])
with open(out, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f, delimiter=";")
    w.writerow(["Дата", "Номер", "Организация", "Контрагент", "Сумма", "Назначение", "Вариант", "Договор-кандидат", "Кандидатов"])
    for r in hang:
        k = (s(r["Орг"]), s(r["Кт"]))
        c = sorted(cand.get(k, []), reverse=True)
        if len(c) == 1: v, d = "один договор в оплатах", c[0][1]
        elif c: v, d = "несколько договоров в оплатах", c[0][1]
        elif len(anyc.get(k, [])) == 1: v, d = "один договор в справочнике", anyc[k][0]
        elif anyc.get(k): v, d = "несколько договоров в справочнике", anyc[k][0]
        else: v, d = "нет договора", ""
        stat[v][0] += 1; stat[v][1] += float(r["Сумма"] or 0)
        w.writerow([s(r["Дата"])[:10], r["Номер"], k[0], k[1], f"{float(r['Сумма'] or 0):.2f}".replace(".", ","), s(r["Назн"])[:150], v, d, len(c) or len(anyc.get(k, []))])
print("строк:", len(hang), "->", out)
for v, (n, sm) in stat.items():
    print(f"{v:35} {n:4} {sm:,.0f}")
