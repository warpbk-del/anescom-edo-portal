print("реквизиты:", want)
for r in q("ВЫБРАТЬ О.Ссылка КАК С, О.Наименование КАК Н ИЗ Справочник.Организации КАК О ГДЕ НЕ О.ПометкаУдаления"):
    o = r["С"]
    print("ОРГ:", r["Н"], "|", "; ".join(f"{n}={s(getattr(o, n))}" for n in want))
