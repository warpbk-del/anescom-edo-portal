# (чтение) обороты 3232 и 3310 ГЕЦЕ ГмбХ (ANESCOM), сальдо на начало
for acc, flt in (('3232', ''), ('3310', 'ГЕЦЕ')):
    print('=====', acc, flt)
    for r in q('ВЫБРАТЬ Х.Регистратор КАК Р, Х.Период КАК П, Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт, Х.Сумма КАК С, Х.СубконтоДт1 КАК СД, Х.СубконтоКт1 КАК СК ИЗ РегистрБухгалтерии.{REG}.ДвиженияССубконто(, , Организация.Наименование ПОДОБНО "%ANESCOM%" И (СчетДт.Код = &А ИЛИ СчетКт.Код = &А), , ) КАК Х УПОРЯДОЧИТЬ ПО Х.Период', А=acc):
        k = s(r['СД']) if r['Дт'] == acc else s(r['СК'])
        if flt and flt not in k.upper(): continue
        print(' ', str(r['П'])[:10], r['Дт'], r['Кт'], f"{float(r['С']):>14,.2f}", s(r['Р'])[:48], '|', k[:25])
