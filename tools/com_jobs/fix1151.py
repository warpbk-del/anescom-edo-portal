orig = q("""ВЫБРАТЬ ПЕРВЫЕ 1 Т.Регистратор КАК Д ИЗ РегистрБухгалтерии.{REG}.ДвиженияССубконто(&Н, &К, СчетДт.Код = "1151" И СчетКт.Код = "6110") КАК Т""",
         Н=datetime.datetime(2026, 5, 31), К=datetime.datetime(2026, 5, 31, 23, 59, 59))[0]["Д"]
print("Образец:", s(orig), "проведён:", orig.Проведен)
rec = {str(r["М"])[:7]: (r["Дт"], r["Кт"]) for r in q("""ВЫБРАТЬ НАЧАЛОПЕРИОДА(Т.Период, МЕСЯЦ) КАК М,
  СУММА(ВЫБОР КОГДА Т.СчетДт.Код = "1151" ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Дт, СУММА(ВЫБОР КОГДА Т.СчетКт.Код = "1151" ТОГДА Т.Сумма ИНАЧЕ 0 КОНЕЦ) КАК Кт
ИЗ РегистрБухгалтерии.{REG}.ДвиженияССубконто(&Н, &К, СчетДт.Код = "1151" ИЛИ СчетКт.Код = "1151") КАК Т СГРУППИРОВАТЬ ПО НАЧАЛОПЕРИОДА(Т.Период, МЕСЯЦ)""",
    Н=datetime.datetime(2026, 6, 1), К=datetime.datetime(2026, 10, 31, 23, 59, 59))}
src = orig.Движения.Хозрасчетный
src.Прочитать()
for mon in (6, 7, 8, 9):  # октябрь — после закрытия месяца
    key = f"2026-{mon:02d}"
    dt, kt = rec.get(key, (0, 0))
    if dt > 0:
        print(key, "уже есть начисление Дт", dt, "— пропуск"); continue
    net = round(kt, 2)
    gross = round(net / 0.85, 2)
    tax = round(gross - net, 2)
    last = calendar.monthrange(2026, mon)[1]
    d = datetime.datetime(2026, mon, last, 12, 0, 0)
    print(f"{key}: поступило {net:,.2f} → начислить брутто {gross:,.2f}, КПН {tax:,.2f}, дата {d:%d.%m.%Y}")
    if DRY:
        continue
    new = orig.Скопировать()
    new.Дата = d
    new.Содержание = f"Вознаграждение по депозитам Народный Банк Казахстана АО период {last:02d}/{mon:02d}/2026"
    new.Комментарий = f"{new.Содержание} [аудит 24.10.2026: не было начисления]"
    new.СуммаОперации = round(gross + tax, 2)
    new.Записать()
    t = src.Выгрузить()
    for i in range(t.Количество()):
        row = t.Получить(i)
        row.Период = d
        row.Регистратор = new.Ссылка
        if row.СчетДт.Код == "1151":
            row.Сумма = gross
            row.Содержание = new.Содержание
        else:
            row.Сумма = tax
    ns = new.Движения.Хозрасчетный
    ns.Загрузить(t)
    ns.Записать()
    if orig.Проведен:
        new.Записать(ib.РежимЗаписиДокумента.Проведение)
    log(f"21-2 1151: создана {s(new.Ссылка)} брутто {gross} КПН {tax} (поступления {net})")
