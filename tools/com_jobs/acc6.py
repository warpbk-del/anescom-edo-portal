# Документы, которым прописаны счета (acc5): статус «Не указаны счета учета» → «К отражению» (кроме 3 поступлений GREENTE без статьи и 3 взаимозачётов — претензии)
E = ib.Перечисления.СтатусыОтраженияДокументовВРеглУчете
R = q('ВЫБРАТЬ О.Регистратор КАК Д ИЗ РегистрСведений.ОтражениеДокументовВРеглУчете КАК О ГДЕ О.Статус = &С', С=E.НеУказаныСчетаУчета)
n = 0
for r in R:
    v = s(r['Д'])
    if not (v.startswith('Списание безналичных ДС GTНФ') or 'переработ' in v.lower()): print('  оставлено:', v[:60]); continue
    ns = ib.РегистрыСведений.ОтражениеДокументовВРеглУчете.СоздатьНаборЗаписей(); ns.Отбор.Регистратор.Установить(r['Д']); ns.Прочитать()
    for i in range(ns.Количество()):
        z = ns.Получить(i)
        if z.Статус == E.НеУказаныСчетаУчета: z.Статус = E.КОтражениюВРеглУчете
    ns.ОбменДанными.Загрузка = True; ns.Записать(); n += 1; print('  → к отражению:', v[:60])
log(f'21: {n} док. «не указаны счета» → «к отражению» после прописки счетов')
