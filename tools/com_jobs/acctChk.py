# Чтение (21-19): ошибки учёта по остаткам на сейчас (копия, данные на 22.10.2026)
import csv, os
from collections import defaultdict
OUT = r"D:\anescom_edo\data\reports\21-15"
D = globals().get("ACC_DATE")  # граница с +6 ч (сдвиг COM); None = на сейчас
P = {"Д": D} if D else {}
AT = "&Д" if D else ""
print("на дату:", D or "сейчас")
# (а) сальдо «не той стороны» по видам счетов
rows = q(f"""ВЫБРАТЬ О.Организация КАК Орг, О.Счет.Код КАК Сч, О.Счет.Наименование КАК Им, О.Счет.Вид КАК Вид,
  СУММА(О.СуммаОстатокДт) КАК Дт, СУММА(О.СуммаОстатокКт) КАК Кт
 ИЗ РегистрБухгалтерии.{{REG}}.Остатки({AT}, , , ) КАК О СГРУППИРОВАТЬ ПО О.Организация, О.Счет.Код, О.Счет.Наименование, О.Счет.Вид""", **P)
print("виды счетов:", sorted({s(r["Вид"]) for r in rows}))
bad = []
for r in rows:
    vid = s(r["Вид"]); dt, kt = float(r["Дт"] or 0), float(r["Кт"] or 0)
    if vid.startswith("Активн") and "асс" not in vid and kt > 1000: bad.append((s(r["Орг"]), s(r["Сч"]), s(r["Им"]), "Кт у активного", kt))
    if vid.startswith("Пассивн") and dt > 1000: bad.append((s(r["Орг"]), s(r["Сч"]), s(r["Им"]), "Дт у пассивного", dt))
bad.sort(key=lambda x: -x[4])
print(f"(а) сальдо не той стороны: {len(bad)}")
for b in bad[:25]: print(f"   {b[0][:22]:22} {b[1]:8} {b[2][:38]:38} {b[3]:16} {b[4]/1e6:10,.2f} млн")
# (б) незачтённые авансы: у одного контрагента одновременно долг и аванс на парных счетах
PAIRS = (("1210", "3510", "покупатель: долг 1210 и аванс 3510"), ("1610", "3310", "поставщик: аванс 1610 и долг 3310"))
for a, b, title in PAIRS:
    rr = q(f"""ВЫБРАТЬ О.Организация КАК Орг, О.Субконто1 КАК К, О.Счет.Код КАК Сч, СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК Ост
     ИЗ РегистрБухгалтерии.{{REG}}.Остатки({AT}, Счет.Код ПОДОБНО "{a}%" ИЛИ Счет.Код ПОДОБНО "{b}%", , ) КАК О
     СГРУППИРОВАТЬ ПО О.Организация, О.Субконто1, О.Счет.Код""", **P)
    m = defaultdict(lambda: [0.0, 0.0])
    for r in rr:
        k = (s(r["Орг"]), s(r["К"]))
        if s(r["Сч"]).startswith(a): m[k][0] += float(r["Ост"] or 0)
        else: m[k][1] += float(r["Ост"] or 0)
    both = [(k, v) for k, v in m.items() if abs(v[0]) > 1000 and abs(v[1]) > 1000 and (v[0] > 0) != (v[1] > 0)]
    off = sum(min(abs(v[0]), abs(v[1])) for _, v in both)
    print(f"(б) {title}: контрагентов {len(both)}, можно зачесть {off/1e6:,.2f} млн")
    for k, v in sorted(both, key=lambda x: -min(abs(x[1][0]), abs(x[1][1])))[:10]:
        print(f"   {k[0][:18]:18} {k[1][:38]:38} {a} {v[0]/1e6:9,.2f}  {b} {v[1]/1e6:9,.2f}")
    with open(os.path.join(OUT, f"19_незачтенные_{a}_{b}.csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";"); w.writerow(["Организация", "Контрагент", a, b])
        for k, v in both: w.writerow([k[0], k[1], f"{v[0]:.2f}".replace(".", ","), f"{v[1]:.2f}".replace(".", ",")])
# (в) касса и банк с Кт-сальдо по субконто
for acc in ("1010", "1030"):
    rr = q(f"""ВЫБРАТЬ О.Организация КАК Орг, О.Субконто1 КАК К, СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК Ост
     ИЗ РегистрБухгалтерии.{{REG}}.Остатки({AT}, Счет.Код ПОДОБНО "{acc}%", , ) КАК О СГРУППИРОВАТЬ ПО О.Организация, О.Субконто1
     ИМЕЮЩИЕ СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) < -1""", **P)
    print(f"(в) {acc} в минусе: {len(rr)}", "; ".join(f"{s(r['Орг'])[:12]} {s(r['К'])[:30]} {float(r['Ост']):,.0f}" for r in rr[:8]))
# (г) зарплата 3350 с Дт-сальдо (переплата) и подотчёт 1251 по сотрудникам
for acc, title in (("3350", "ЗП: переплата сотруднику (Дт 3350)"), ("1251", "подотчёт: долг сотрудника (Дт 1251)")):
    rr = q(f"""ВЫБРАТЬ О.Организация КАК Орг, О.Субконто1 КАК К, СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК Ост
     ИЗ РегистрБухгалтерии.{{REG}}.Остатки({AT}, Счет.Код ПОДОБНО "{acc}%", , ) КАК О СГРУППИРОВАТЬ ПО О.Организация, О.Субконто1
     ИМЕЮЩИЕ СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) > 1000""", **P)
    tot = sum(float(r["Ост"]) for r in rr)
    print(f"(г) {title}: {len(rr)} чел., {tot/1e6:,.2f} млн;", "; ".join(f"{s(r['К'])[:25]} {float(r['Ост']):,.0f}" for r in sorted(rr, key=lambda r: -float(r['Ост']))[:6]))
print("CSV:", OUT)
