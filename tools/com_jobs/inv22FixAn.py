# 22-И (КОПИЯ ANESCOM): проверка/исправление «АналитикаУчетаНоменклатуры» в созданных 25.10 документах
# (строки заполнялись по образцу → аналитика могла скопироваться с чужого товара/склада).
# MODE="check" — печать; MODE="fix" — очистить аналитику, записать (Запись) → печать что заполнилось; затем провести.
import datetime
MODE = globals().get("MODE", "check")
N, K = datetime.datetime(2026, 9, 8), datetime.datetime(2026, 9, 8, 23, 59, 59)
docs = []
docs += [r["Р"] for r in q('ВЫБРАТЬ Д.Ссылка КАК Р ИЗ Документ.ПередачаСырьяПереработчику КАК Д ГДЕ Д.Дата МЕЖДУ &Н И &К И Д.Комментарий ПОДОБНО "22-И%"', Н=N, К=K)]
docs += [r["Р"] for r in q('ВЫБРАТЬ Д.Ссылка КАК Р ИЗ Документ.ПеремещениеТоваров КАК Д ГДЕ Д.Дата МЕЖДУ &Н И &К И Д.Комментарий ПОДОБНО "22-И%"', Н=N, К=K)]
docs += [r["Р"] for r in q('ВЫБРАТЬ Д.Ссылка КАК Р ИЗ Документ.СписаниеНедостачТоваров КАК Д ГДЕ Д.Дата МЕЖДУ &Н И &К И Д.Номер ПОДОБНО "%000009"', Н=N, К=K)]
def show(o, tag):
    bad = 0
    for i in range(o.Товары.Количество()):
        r = o.Товары.Получить(i); n = s(r.Номенклатура).strip(); a = s(r.АналитикаУчетаНоменклатуры)
        ok = a.startswith(n[:25]); bad += 0 if ok else 1
        if i < 3 or not ok: print(f"   {tag} {'OK ' if ok else 'ПЛОХО'} | {n[:45]} | аналитика: {a[:70]}")
    print(f"   {tag}: строк {o.Товары.Количество()}, с чужой аналитикой {bad}")
    return bad
for d in docs:
    o = d.ПолучитьОбъект(); print("==", s(d), "| проведён", d.Проведен)
    bad = show(o, "было")
    if MODE == "fix" and bad:
        posted = o.Проведен
        if posted: o.Записать(ib.РежимЗаписиДокумента.ОтменаПроведения); o = d.ПолучитьОбъект()
        for i in range(o.Товары.Количество()):
            o.Товары.Получить(i).АналитикаУчетаНоменклатуры = None
        o.Записать(ib.РежимЗаписиДокумента.Запись); o = d.ПолучитьОбъект()
        if show(o, "после записи") == 0:
            log(f"22-И: {s(d)} — аналитика пересчитана")
        else:
            print("   аналитика не заполнилась автоматически — документ оставлен НЕпроведённым")
print("ГОТОВО inv22FixAn", MODE)
