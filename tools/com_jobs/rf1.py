        ok += 1
        if MODE == "one" or ok % 20 == 0: print(f"  {s(d)[-45:]} → проводок {n}, статус {s(st[0]['С']) if st else '-'}, ответ {s(res)[:40]}")
        log(f"21-29m отражён в РУ: {s(d)} проводок {n}")
