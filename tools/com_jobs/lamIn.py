# 22-И (чтение, копия ANESCOM): что ANESCOM получил с ламинации по документам 2025–2026, по товарам —
# «Поступление от переработчика» и «Приобретение товаров и услуг» (склад «Ламинация Автокомп»), плюс излишки на этом складе.
# Вывод одной строкой на товар: имя | поступл.от перераб. | приобретение | излишки — для сверки с «АК-» недостачей АВТОКОМП.
from collections import defaultdict
N, K = datetime.datetime(2025, 1, 1), datetime.datetime(2026, 12, 31, 23, 59, 59)
S = q('ВЫБРАТЬ С.Ссылка КАК С ИЗ Справочник.Склады КАК С ГДЕ С.Наименование ПОДОБНО "%Ламинац%"')[0]["С"]
agg = defaultdict(lambda: [0.0, 0.0, 0.0])
for r in q("""ВЫБРАТЬ Т.Номенклатура.Наименование КАК Н, ТИПЗНАЧЕНИЯ(Т.Регистратор) КАК Т, ГОД(Т.Период) КАК Г, СУММА(Т.ВНаличииПриход) КАК П
ИЗ РегистрНакопления.ТоварыНаСкладах.ОстаткиИОбороты(&Н, &К, Регистратор, , Склад = &С) КАК Т
СГРУППИРОВАТЬ ПО Т.Номенклатура.Наименование, ТИПЗНАЧЕНИЯ(Т.Регистратор), ГОД(Т.Период)""", Н=N, К=K, С=S):
    t = s(r["Т"]); i = 0 if "переработчик" in t.lower() else 1 if "Приобретение" in t else 2 if "излишк" in t.lower() else None
    if i is None or r["Г"] != 2026: continue
    agg[s(r["Н"])][i] += float(r["П"] or 0)
keys = [k for k in agg if any(w in k for w in ("Helios", "Bauline", "Standart", "Дверная створка", "Соединительная планка", "W45", "W65", "W50", "D45", "D65", "D72", "F50", "СТН-", "БПК"))]
print(f"== 2026, склад Ламинация Автокомп: товаров {len(keys)}; поступл.от перераб. {sum(agg[k][0] for k in keys):,.1f}; приобретение {sum(agg[k][1] for k in keys):,.1f}; излишки {sum(agg[k][2] for k in keys):,.1f}")
for k in sorted(keys, key=lambda k: -(agg[k][0] + agg[k][1])):
    a = agg[k]
    if a[0] + a[1] + a[2] > 0: print(f"{k[:75]}|{a[0]:g}|{a[1]:g}|{a[2]:g}")
