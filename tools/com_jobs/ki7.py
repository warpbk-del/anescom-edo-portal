X = ib.XMLСтрока
def attr(o, n):
    try: return getattr(o, n)
    except Exception: return '—'
# все виды КИ: группа, имя предопределённых данных, ИмяПредопределенногоВида (БСП 3), используется, пометка
rows = q('ВЫБРАТЬ ВКИ.Ссылка КАК С, ВКИ.Наименование КАК Нм, ВКИ.Родитель КАК Р, ВКИ.ЭтоГруппа КАК Гр ИЗ Справочник.ВидыКонтактнойИнформации КАК ВКИ')
use = {}
for cat in ['ФизическиеЛица', 'Партнеры', 'КонтактныеЛицаПартнеров', 'Контрагенты', 'Организации']:
    for x in q('ВЫБРАТЬ КИ.Вид КАК Вд, КОЛИЧЕСТВО(*) КАК Кл ИЗ Справочник.' + cat + '.КонтактнаяИнформация КАК КИ СГРУППИРОВАТЬ ПО КИ.Вид'):
        use[(cat, X(x['Вд']))] = x['Кл']
for x in sorted(rows, key=lambda r: (s(r['Р']), r['Нм'])):
    o = x['С']
    if 'изическ' not in s(x['Р']) and 'изическ' not in x['Нм']:
        continue
    print('K', s(x['Р'])[:22], '|', x['Нм'][:34], '| pd', attr(o, 'ИмяПредопределенныхДанных'), '| pv', attr(o, 'ИмяПредопределенногоВида'),
          '| исп', attr(o, 'Используется'), '| пм', attr(o, 'ПометкаУдаления'), '| гр', x['Гр'], '| строк', use.get(('ФизическиеЛица', X(o)), 0))
# строки КИ у физлица НФ-999
