# (только чтение, ANESCOM_FIX) Счета учёта для документов «Не указаны счета учёта»: образцы из базы.
import collections
MDR = MD.РегистрыСведений
# 1) документы со статусом НеУказаныСчетаУчета
EN = ib.Перечисления.СтатусыОтраженияДокументовВРеглУчете
for r in q('ВЫБРАТЬ О.Регистратор КАК Д, О.Организация КАК О ИЗ РегистрСведений.ОтражениеДокументовВРеглУчете КАК О ГДЕ О.Статус = &С', С=EN.НеУказаныСчетаУчета):
    print('NOACC', s(r['Д'])[:70], '|', s(r['О'])[:25])
# 2) регистры настроек со словом «Переработ» в полях
for i in range(MDR.Количество()):
    m = MDR.Получить(i); fl = []
    for coll in (m.Измерения, m.Ресурсы, m.Реквизиты):
        fl += [coll.Получить(j).Имя for j in range(coll.Количество())]
    pf = [f for f in fl if 'ереработ' in f]
    if pf and ('Счет' in m.Имя or 'Счета' in m.Имя or 'Отражен' in m.Имя or 'Настройк' in m.Имя):
        print('REG', m.Имя, '| поля', fl[:12], '| перераб.', pf)
        for f in pf:
            try:
                c = collections.Counter()
                for r in q(f'ВЫБРАТЬ Т.{f} КАК В ИЗ РегистрСведений.{m.Имя} КАК Т'):
                    v = r['В']; c[(v.Код + ' ' + v.Наименование[:30]) if hasattr(v, 'Код') else s(v)] += 1
                print('   ', f, c.most_common(8))
            except Exception as e: print('   ERR', f, str(e)[-80:])
# 3) прошлые штрафы/пени: проводки списаний ДС с «штраф»/«пен» в назначении
c = collections.Counter()
for r in q('ВЫБРАТЬ Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт, Х.Сумма КАК С, Х.Регистратор КАК Р ИЗ РегистрБухгалтерии.{REG} КАК Х '
           'ГДЕ Х.Регистратор ССЫЛКА Документ.СписаниеБезналичныхДенежныхСредств И (ВЫРАЗИТЬ(Х.Регистратор КАК Документ.СписаниеБезналичныхДенежныхСредств).НазначениеПлатежа ПОДОБНО "%штраф%" '
           'ИЛИ ВЫРАЗИТЬ(Х.Регистратор КАК Документ.СписаниеБезналичныхДенежныхСредств).НазначениеПлатежа ПОДОБНО "%пен%")'):
    c[(r['Дт'], r['Кт'])] += 1
print('ШТРАФЫ/ПЕНИ проводки (Дт,Кт):', c.most_common(10))
c = collections.Counter()
for r in q('ВЫБРАТЬ Х.СчетДт.Код КАК Дт, Х.СчетКт.Код КАК Кт ИЗ РегистрБухгалтерии.{REG} КАК Х ГДЕ Х.Содержание ПОДОБНО "%штраф%" ИЛИ Х.Содержание ПОДОБНО "%пен%"'):
    c[(r['Дт'], r['Кт'])] += 1
print('ШТРАФЫ/ПЕНИ по содержанию:', c.most_common(10))
# 4) налог «Прочие налоги и сборы» — где хранится счёт
for i in range(MD.Справочники.Количество()):
    m = MD.Справочники.Получить(i)
    if 'алог' not in m.Имя: continue
    try:
        rr = q(f'ВЫБРАТЬ Т.Ссылка КАК С ИЗ Справочник.{m.Имя} КАК Т ГДЕ Т.Наименование ПОДОБНО "%Прочие налоги%"')
    except Exception: continue
    for r in rr:
        o = r['С']; acc = []
        for j in range(m.Реквизиты.Количество()):
            a = m.Реквизиты.Получить(j)
            if 'Счет' in a.Имя: acc.append(f'{a.Имя}={s(getattr(o, a.Имя))}')
        print('TAX', m.Имя, s(o), acc)
        # как настроены другие налоги этого справочника
        for x in q(f'ВЫБРАТЬ ПЕРВЫЕ 15 Т.Ссылка КАК С ИЗ Справочник.{m.Имя} КАК Т ГДЕ НЕ Т.ПометкаУдаления'):
            print('   ', s(x['С'])[:40], [f'{m.Реквизиты.Получить(j).Имя}={s(getattr(x["С"], m.Реквизиты.Получить(j).Имя))}' for j in range(m.Реквизиты.Количество()) if 'Счет' in m.Реквизиты.Получить(j).Имя])
