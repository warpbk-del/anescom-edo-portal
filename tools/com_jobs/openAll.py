# (чтение) все счета, 1421/142x/313x и 5xxx: БП на 31.12.2024 против КА (начальный остаток 01.2025), ANESCOM.
BPREG = globals().get('BPREG_NAME', 'Типовой')
z = ib_bp.NewObject('Запрос')
z.Текст = 'ВЫБРАТЬ Т.Счет.Код КАК С, Т.Организация КАК О, СУММА(Т.СуммаОстатокДт - Т.СуммаОстатокКт) КАК Б ИЗ РегистрБухгалтерии.' + BPREG + '.Остатки(&Д, , , ) КАК Т СГРУППИРОВАТЬ ПО Т.Счет.Код, Т.Организация'
z.УстановитьПараметр('Д', datetime.datetime(2025, 1, 1, 5)); sel = z.Выполнить().Выбрать(); BP = {}
while sel.Следующий():
    o = ib_bp.String(sel.О).upper()
    if 'ANESCOM' in o or 'АНЕСКОМ' in o: BP[sel.С.strip()] = BP.get(sel.С.strip(), 0) + (sel.Б or 0)
KA = {}
for r in q('ВЫБРАТЬ Т.Счет.Код КАК С, СУММА(Т.СуммаОстатокДт - Т.СуммаОстатокКт) КАК Б ИЗ РегистрБухгалтерии.{REG}.Остатки(&Н, , , Организация.Наименование ПОДОБНО "%ANESCOM%") КАК Т СГРУППИРОВАТЬ ПО Т.Счет.Код', Н=datetime.datetime(2025, 1, 1, 6)):
    KA[r['С'].strip()] = KA.get(r['С'].strip(), 0) + (r['Б'] or 0)
tb=ta=0
for k in sorted(set(BP)|set(KA)):
    b,a=BP.get(k,0),KA.get(k,0); tb+=b; ta+=a
    if abs(a-b)>1000: print(f'  {k:8s} БП {b:>18,.2f} | КА {a:>18,.2f} | КА−БП {a-b:>16,.2f}')
print('ИТОГО БП',f'{tb:,.2f}','КА',f'{ta:,.2f}')
