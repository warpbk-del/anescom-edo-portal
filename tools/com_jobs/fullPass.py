# 21-21 ПОЛНЫЙ ПРОХОД (только чтение). Точка контроля — 30.06.2025 (последний перезакрытый месяц копии), даты +6 ч (сдвиг COM).
# Каждый раздел: основной расчёт + сверка вторым способом. Итог — в консоль и CSV D:\anescom_edo\data\reports\21-21\
import csv, os
from collections import defaultdict
OUT = r"D:\anescom_edo\data\reports\21-21"; os.makedirs(OUT, exist_ok=True)
D = datetime.datetime(2025, 7, 1, 6)        # «на конец 30.06.2025»
N0 = datetime.datetime(2025, 1, 1, 6)
def csvw(name, head, rows):
    with open(os.path.join(OUT, name + ".csv"), "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";"); w.writerow(head)
        for r in rows: w.writerow([f"{x:.2f}".replace(".", ",") if isinstance(x, float) else x for x in r])
def sec(t): print("\n=== " + t)
def bal(acc_like, dims="О.Организация, О.Субконто1"):
    return q(f"""ВЫБРАТЬ {dims.replace('О.Организация', 'О.Организация КАК Орг').replace('О.Субконто1', 'О.Субконто1 КАК С1').replace('О.Счет.Код', 'О.Счет.Код КАК Сч')},
      СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК Ост ИЗ РегистрБухгалтерии.{{REG}}.Остатки(&Д, Счет.Код ПОДОБНО "{acc_like}", , ) КАК О
      СГРУППИРОВАТЬ ПО {dims}""", Д=D)

# 1. Сальдо «не той стороны» по субконто (активные с Кт, пассивные с Дт), > 10 000
sec("1. Сальдо не той стороны (по контрагенту/сотруднику/кассе)")
rows = q("""ВЫБРАТЬ О.Организация КАК Орг, О.Счет.Код КАК Сч, О.Счет.Вид КАК Вид, О.Субконто1 КАК С1, СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК Ост
 ИЗ РегистрБухгалтерии.{REG}.Остатки(&Д, , , ) КАК О СГРУППИРОВАТЬ ПО О.Организация, О.Счет.Код, О.Счет.Вид, О.Субконто1""", Д=D)
wrong = [(s(r["Орг"]), s(r["Сч"]), s(r["С1"]), float(r["Ост"])) for r in rows
         if (s(r["Вид"]) == "Активный" and float(r["Ост"]) < -10000) or (s(r["Вид"]) == "Пассивный" and float(r["Ост"]) > 10000)]
by = defaultdict(lambda: [0, 0.0])
for o, a, c, v in wrong: by[a][0] += 1; by[a][1] += v
for a, (n, v) in sorted(by.items(), key=lambda x: -abs(x[1][1])): print(f"   {a:8} строк {n:4}  {v/1e6:10,.2f} млн")
csvw("1_сальдо_не_той_стороны", ["Орг", "Счёт", "Субконто1", "Сальдо"], wrong)

# 2. Расчёты с клиентами: регл. (1210+3510) vs опер. (РасчетыСКлиентами) — по контрагенту
sec("2. Клиенты: незачтённые авансы и сверка БУ с оперативным учётом")
b = defaultdict(lambda: [0.0, 0.0])
for r in bal("1210%"): b[(s(r["Орг"]), s(r["С1"]))][0] += float(r["Ост"])
for r in bal("3510%"): b[(s(r["Орг"]), s(r["С1"]))][1] += float(r["Ост"])
mir = [(k, v) for k, v in b.items() if v[0] > 1000 and v[1] < -1000]
print(f"   долг 1210 и аванс 3510 одновременно: {len(mir)} контрагентов, к зачёту {sum(min(v[0], -v[1]) for _, v in mir)/1e6:,.2f} млн")
op = defaultdict(float)
for r in q("""ВЫБРАТЬ Р.АналитикаУчетаПоПартнерам.Организация КАК Орг, Р.АналитикаУчетаПоПартнерам.Контрагент КАК К, СУММА(Р.СуммаОстаток) КАК О
  ИЗ РегистрНакопления.РасчетыСКлиентами.Остатки(&Д, ) КАК Р СГРУППИРОВАТЬ ПО Р.АналитикаУчетаПоПартнерам.Организация, Р.АналитикаУчетаПоПартнерам.Контрагент""", Д=D):
    op[(s(r["Орг"]), s(r["К"]))] += float(r["О"] or 0)
diff = [(k[0], k[1], b[k][0] + b[k][1], op.get(k, 0.0)) for k in set(b) | set(op) if abs(b[k][0] + b[k][1] - op.get(k, 0.0)) > 1000]
print(f"   нетто БУ (1210+3510) ≠ оперативный долг: {len(diff)} контрагентов, сумма расхождений {sum(abs(x[2]-x[3]) for x in diff)/1e6:,.2f} млн")
csvw("2_клиенты_зачет", ["Орг", "Контрагент", "1210", "3510"], [(k[0], k[1], v[0], v[1]) for k, v in mir])
csvw("2_клиенты_БУ_vs_опер", ["Орг", "Контрагент", "БУ нетто", "Опер"], diff)

# 3. Поставщики: то же для 1610/3310 и РасчетыСПоставщиками
sec("3. Поставщики: незачтённые авансы и сверка БУ с оперативным")
b = defaultdict(lambda: [0.0, 0.0])
for r in bal("1610%"): b[(s(r["Орг"]), s(r["С1"]))][0] += float(r["Ост"])
for r in bal("3310%"): b[(s(r["Орг"]), s(r["С1"]))][1] += float(r["Ост"])
mir = [(k, v) for k, v in b.items() if v[0] > 1000 and v[1] < -1000]
print(f"   аванс 1610 и долг 3310 одновременно: {len(mir)}, к зачёту {sum(min(v[0], -v[1]) for _, v in mir)/1e6:,.2f} млн")
op = defaultdict(float)
for r in q("""ВЫБРАТЬ Р.АналитикаУчетаПоПартнерам.Организация КАК Орг, Р.АналитикаУчетаПоПартнерам.Контрагент КАК К, СУММА(Р.СуммаОстаток) КАК О
  ИЗ РегистрНакопления.РасчетыСПоставщиками.Остатки(&Д, ) КАК Р СГРУППИРОВАТЬ ПО Р.АналитикаУчетаПоПартнерам.Организация, Р.АналитикаУчетаПоПартнерам.Контрагент""", Д=D):
    op[(s(r["Орг"]), s(r["К"]))] += float(r["О"] or 0)
diff = [(k[0], k[1], b[k][0] + b[k][1], op.get(k, 0.0)) for k in set(b) | set(op) if abs(b[k][0] + b[k][1] + op.get(k, 0.0)) > 1000 and abs(b[k][0] + b[k][1] - op.get(k, 0.0)) > 1000]
print(f"   нетто БУ ≠ оперативный: {len(diff)} контрагентов")
csvw("3_поставщики_БУ_vs_опер", ["Орг", "Контрагент", "БУ нетто", "Опер"], diff)

# 4. Деньги: касса/банк в минусе на конец каждого месяца 01–06.2025 (по кассе/счёту)
sec("4. Касса и банк в минусе на конец месяцев 01–06.2025")
neg = []
for m in range(1, 7):
    d = datetime.datetime(2025, m + 1, 1, 6)
    for r in q("""ВЫБРАТЬ О.Счет.Код КАК Сч, О.Организация КАК Орг, О.Субконто1 КАК С1, СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) КАК Ост
      ИЗ РегистрБухгалтерии.{REG}.Остатки(&Д, Счет.Код ПОДОБНО "10%", , ) КАК О СГРУППИРОВАТЬ ПО О.Счет.Код, О.Организация, О.Субконто1
      ИМЕЮЩИЕ СУММА(О.СуммаОстатокДт - О.СуммаОстатокКт) < -1""", Д=d):
        neg.append((f"{m:02d}.2025", s(r["Сч"]), s(r["Орг"]), s(r["С1"]), float(r["Ост"])))
print(f"   случаев: {len(neg)}", "; ".join(f"{x[0]} {x[1]} {x[3][:25]} {x[4]:,.0f}" for x in neg[:8]))
csvw("4_деньги_минус", ["Месяц", "Счёт", "Орг", "Касса/счёт", "Сальдо"], neg)

# 5. Склад: минусы в ТоварыНаСкладах / ТоварыОрганизаций на конец 06.2025 и сейчас
sec("5. Склад: отрицательные остатки")
for reg, f in (("ТоварыНаСкладах", "ВНаличииОстаток"), ("ТоварыОрганизаций", "КоличествоОстаток")):
    for dd, lab in ((D, "30.06.2025"), (None, "сейчас")):
        try:
            r = q(f"ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.{reg}.Остатки({'&Д' if dd else ''}, ) КАК Р ГДЕ Р.{f} < 0", **({"Д": dd} if dd else {}))[0]["К"]
            print(f"   {reg} {lab}: строк с минусом {r}")
        except Exception as e: print(f"   {reg}: ошибка {str(e)[-80:]}")

# 6. Зарплата и подотчёт по сотрудникам (БУ) — сверка с оперативным регистром расчётов с персоналом
sec("6. Зарплата (3350 Дт = переплата) и подотчёт 1251")
for acc in ("3350%", "1251%"):
    rr = [(s(r["Орг"]), s(r["С1"]), float(r["Ост"])) for r in bal(acc) if float(r["Ост"]) > 1000]
    print(f"   {acc[:4]}: {len(rr)} чел., {sum(x[2] for x in rr)/1e6:,.2f} млн")
    csvw(f"6_{acc[:4]}", ["Орг", "Сотрудник", "Дт сальдо"], rr)

