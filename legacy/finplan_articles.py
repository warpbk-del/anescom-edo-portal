def article_of(statya: str, naznach: str = "") -> str:
    """Код статьи: сначала по «Статье расхода», если её нет — по «Назначению платежа»."""
    for src in (statya, naznach):
        s = (src or "").lower()
        if not s or "не установлено" in s or s == "nan":
            continue
        for key, code in RULES:
            if key in s:
                return code
    return "ADM.08"


