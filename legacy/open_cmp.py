KA = {  # ANESCOM, сальдо на 01.01.2025 (Дт−Кт), копия KA2026, выгрузка аудита 24.10.2026
"0000": 3216170.42, "1010": 232252.00, "1021": 2170000.00, "1030": 59819123.49, "1050": 1230488.05,
"1060": 266878323.00, "1210": 224623999.37, "1251": 4823906.93, "1310": 3007286.16, "1330": 1184761667.12,
"1411": 72766499.00, "1421": 48163421.30, "1423.1": 1181002.19, "1430": 402080.41, "1710": 436932672.61,
"1720": 1027562.94, "2412": 133046638.89, "3120": -552378.63, "3132.3": -94935.00, "3150": -368830.00,
"3180": -7263.00, "3190": -2625.00, "3211": -290538.00, "3212": -132619.00, "3213": -194494.00,
"3221": -947684.00, "3250": -107898.00, "3310": -98471760.55, "3385": -18642.00, "3387": -82861340.00,
"3510": -361853755.27, "5030": -150000.00, "5520": -1190000.00, "5610": -1897038331.43}

bp = defaultdict(float)
last = ""
for r in rows("bp", "acc_Типовой", ["Период", "СчетДт", "СчетКт", "Сумма"]):
    p = r["Период"][:10]
    if p > "2024-12-31":
        continue
    last = max(last, p)
    s = num(r["Сумма"])
    bp[r["СчетДт"]] += s
    bp[r["СчетКт"]] -= s
out(f"БП: последняя дата проводок ≤2024: {last}")
accs = sorted(set(k for k, v in bp.items() if abs(v) > 0.5) | set(KA))
out("счёт | БП 31.12.2024 | КА 01.01.2025 | разница КА−БП")
tb = tk = 0
for a in accs:
    b, k = bp.get(a, 0.0), KA.get(a, 0.0)
    tb += b; tk += k
    flag = "" if abs(k - b) < 1 else "  <<<"
    out(f"{a} | {b:,.2f} | {k:,.2f} | {k - b:,.2f}{flag}")
out(f"ИТОГО | {tb:,.2f} | {tk:,.2f}")
