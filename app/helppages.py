def _page(request: Request, key: str):
    from . import main as m
    title, blocks = PAGES[key]
    return m.templates.TemplateResponse("help.html", {
        "request": request, "brand": config.BRAND, "company": config.COMPANY, "base": m._root(),
        "title": title, "blocks": blocks, "key": key, "pages": [(k, v[0]) for k, v in PAGES.items()],
        "portal": config.PUBLIC_BASE_URL})


@router.get("/help", response_class=HTMLResponse)
def help_index(request: Request):
    from . import main as m
    return m.templates.TemplateResponse("help.html", {
        "request": request, "brand": config.BRAND, "company": config.COMPANY, "base": m._root(),
        "title": "Инструкции", "blocks": [], "key": "", "pages": [(k, v[0]) for k, v in PAGES.items()],
        "portal": config.PUBLIC_BASE_URL})


@router.get("/help/{key}", response_class=HTMLResponse)
def help_page(request: Request, key: str):
    if key not in PAGES:
        return help_index(request)
    return _page(request, key)
